"""
Inference-time MCTS ablation study implementing §3.2-3.6 as active MCTS signals.

Three phases:
  Phase 1: Pilot — measure empirical σ_G and Δ_rank to derive recommended D (§3.3)
  Phase 2: Ablation — run theory-anchored configs on 1-2 example problems
  Phase 3: Report — theory vs empirical comparison + W&B tables

Key theoretical signals used:
  §3.2  Bias bound:         |V̂(D,b) - V*| ≤ γ^(D+1) × Δ̄_G
  §3.3  Ranking reliable:   Δ_rank > 2γ^(D+1) σ_G   ← adaptive convergence criterion
  §3.4  Coverage miss-rate: 1 - b/5 (0% with stratified b≥5)
  §3.5  Cost-benefit:       D=1, b=5 default; 5 FEA/step
  §3.6  LLM agreement:      ρ = P(LLM top == tree-best)

Usage:
    python scripts/eval_mcts_inference.py \\
        --model-config configs/model/qwen3_14b.yaml \\
        --checkpoint checkpoints/sft/warmstart_qwen3_14b_39083858/final \\
        --problem-ids auto_problem_000 auto_problem_001 \\
        --pilot-steps 3 --max-depth 3 --max-steps 9 \\
        --output logs/posterior/mcts_inference_${SLURM_JOB_ID}.jsonl
"""

