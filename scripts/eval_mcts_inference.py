    n_depth_expansions: int      # extra levels beyond D_start in adaptive
    # §3.2
    delta_g_per_candidate: list[float]   # Δ_G(T(s,a_k)) per candidate
    delta_g_mean: float
    # §3.4
    class_coverage: int          # distinct action classes in candidate set
    # §3.6
