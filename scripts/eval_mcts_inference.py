    prompt_last_user_message: str        # last user message (truncated to 400 chars)
    candidates_raw: list[str]            # raw LLM outputs for all K candidates
    candidates_parsed: list[str]         # parsed grammar actions (empty if parse failed)
    candidates_classes: list[str]
