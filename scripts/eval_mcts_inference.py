def load_model_config(config_path: str | Path):
    config_path = Path(config_path)
    cfg = OmegaConf.load(config_path)
    merged = OmegaConf.create()
    for default in cfg.get("defaults", []):
        if isinstance(default, str):
            default_name = default
        elif isinstance(default, dict) and len(default) == 1:
            _, default_name = next(iter(default.items()))
        else:
            continue
        if default_name in {"_self_", None}:
            continue
        default_path = config_path.parent / f"{default_name}.yaml"
        if default_path.exists():
            merged = OmegaConf.merge(merged, OmegaConf.load(default_path))
    cfg_no_defaults = OmegaConf.create(
        {k: v for k, v in OmegaConf.to_container(cfg, resolve=False).items() if k != "defaults"}
    )
    return OmegaConf.merge(merged, cfg_no_defaults)


def _assert_model_on_cuda(model) -> None:
    device_map = getattr(model, "hf_device_map", None)
    if device_map:
        unique_devices = {str(d) for d in device_map.values()}
        # Accept integer device IDs (0, 1, ...) or "cuda:N" strings
        if any(d.startswith("cuda") or d.isdigit() for d in unique_devices):
            return
        raise RuntimeError(f"Model not on CUDA: {device_map}")
    first = next(model.parameters()).device
    if first.type != "cuda":
        raise RuntimeError(f"Model not on CUDA: first param on {first}")


def _analytic_fea_per_step(K: int, D: int, b1: int, bd: int) -> int:
    """FEA calls per MCTS step: K root transitions + b1*(1 + bd + ... bd^(D-1)) subtree calls."""
    if D == 0:
        return K
    subtree = b1 * sum(bd ** d for d in range(D))
    return K + subtree


def _extract_thinking(raw: str) -> str:
    m = re.search(r"<think>(.*?)</think>", raw, re.DOTALL)
    return (m.group(1)[:400] if m else "")


def _std_safe(values: list[float]) -> float:
    return statistics.stdev(values) if len(values) >= 2 else 0.0


def _delta_rank_from_tree(tree) -> float:
    vals = sorted(tree.action_values.values(), reverse=True)
    return (vals[0] - vals[1]) if len(vals) >= 2 else float("inf")


def _compute_sigma_g(tree_base, tree_deeper) -> float:
    """σ_G = std_k[ max(0, V̂_D+1(s,a_k) - V̂_D(s,a_k)) ] across shared candidates."""
    shared = set(tree_base.action_values) & set(tree_deeper.action_values)
    if len(shared) < 2:
        return 0.0
    delta_g = [
        max(0.0, tree_deeper.action_values[a] - tree_base.action_values[a])
        for a in shared
    ]
    return _std_safe(delta_g)


def _delta_g_per_candidate(tree_base, tree_deeper) -> list[float]:
    shared = set(tree_base.action_values) & set(tree_deeper.action_values)
    return [
        max(0.0, tree_deeper.action_values[a] - tree_base.action_values[a])
        for a in shared
    ]


def _run_tree(evaluator, context, candidates, depth: int, b1: int, bd: int, gamma: float, adaptive_thresh=None):
    from llm_finetune.training.rl.posterior.tree_expansion import evaluate_tree
    return evaluate_tree(
        root_node=context,
        root_candidates=candidates,
        transition_fn=evaluator._transition,
        continuation_fn=evaluator._greedy_continuation,
        sampler_fn=evaluator._sample_for_tree,
        depth=depth,
        level1_branching=b1,
        deeper_branching=bd,
        gamma=gamma,
        adaptive_entropy_threshold=adaptive_thresh,
        stratified=True,
    )


def _log_llm_io(
    wandb_io_table,
    llm_io_path: Optional[Path],
    problem_id: str,
    ablation_key: str,
    t: int,
    attempts: list[dict],
    messages: list[dict],
) -> None:
    """Append one row per decode attempt to W&B and a local JSONL log."""
    from llm_finetune.training.rl.posterior.features import action_class

    last_user = next(
        (m["content"][:400] for m in reversed(messages) if m.get("role") == "user"), ""
    )
    for attempt in attempts:
        raw = attempt.get("raw_text", "")
        parsed_action = attempt.get("parsed_action", "")
        parsed_class = action_class(parsed_action) if parsed_action else ""
        thinking = _extract_thinking(raw)
        record = LLMIORecord(
            problem_id=problem_id,
            ablation_key=ablation_key,
            step_t=t,
            candidate_rank=int(attempt.get("rank", 0) or 0),
            source=attempt.get("source", ""),
            parse_success=bool(attempt.get("parse_success", False)),
            parsed_action=parsed_action,
            action_class=parsed_class,
            raw_output=raw,
            thinking=thinking,
            prompt_messages=messages,
            prompt_last_user_message=last_user,
        )
        if llm_io_path is not None:
            with llm_io_path.open("a", encoding="utf-8") as f:
                f.write(json.dumps(asdict(record)) + "\n")
        if wandb_io_table is None:
            continue
        try:
            wandb_io_table.add_data(
                problem_id, ablation_key, t, record.candidate_rank,
                last_user,
                raw[:600],
                thinking,
                parsed_action,
                parsed_class,
                record.parse_success,
                record.source,
            )
        except Exception as exc:
            log.debug("W&B IO table add_data failed: %s", exc)


# ── Phase 1: Pilot ─────────────────────────────────────────────────────────────

def pilot_estimate(
    evaluator,
    problem_spec: dict,
    args,
    wandb_io_table=None,
    llm_io_path: Optional[Path] = None,
) -> dict:
    """
    Run D=0..max_depth trees on pilot_steps steps to estimate σ_G, Δ_rank,
    and derive the minimum D that achieves reliability_target fraction reliable steps.
    """
    log.info("PILOT: problem_id=%s pilot_steps=%d max_depth=%d",
             problem_spec.get("problem_id"), args.pilot_steps, args.max_depth)
    if hasattr(evaluator, "configure_generation_logging"):
        evaluator.configure_generation_logging(ablation_key="pilot")

    context = evaluator._initial_context(problem_spec)
    if context is None:
        log.warning("PILOT: could not initialize context for %s", problem_spec.get("problem_id"))
        return {
            "recommended_D": 1,
            "mean_delta_rank": 0.0,
            "per_depth": {},
            "pilot_steps_run": 0,
            "had_candidates": False,
        }

    gamma = args.gamma
    sigma_g_per_depth: dict[int, list[float]] = collections.defaultdict(list)
    delta_rank_steps: list[float] = []
    trees_at_step: list[dict[int, object]] = []

    for t in range(args.pilot_steps):
        if context is None:
            break
        if hasattr(evaluator, "configure_generation_logging"):
            evaluator.configure_generation_logging(ablation_key="pilot", step_t=t)
        messages = context.build_messages(evaluator.formatter)
        candidates, top_action, attempts = evaluator.generate_candidates(
            context,
            num_candidates=args.candidate_count,
            include_greedy=True,
            stage_label=f"pilot step {t + 1}/{args.pilot_steps}",
        )
        _log_llm_io(
            wandb_io_table,
            None,
            problem_spec.get("problem_id", "unknown"),
            "pilot",
            t,
            attempts,
            messages,
        )
        if not candidates:
            log.warning("PILOT step %d: no candidates", t)
            return {
                "recommended_D": 1,
                "mean_delta_rank": 0.0,
                "per_depth": {},
                "pilot_steps_run": 0,
                "had_candidates": False,
            }

        # Run trees at each depth
        trees: dict[int, object] = {}
        for D in range(args.max_depth + 1):
            trees[D] = _run_tree(evaluator, context, candidates, D,
                                 args.level1_branching, args.deeper_branching, gamma)

        trees_at_step.append(trees)

        # σ_G[D] from comparing V̂_D and V̂_{D+1}
        for D in range(args.max_depth):
            dg = _delta_g_per_candidate(trees[D], trees[D + 1])
            sigma_g_per_depth[D].append(_std_safe(dg))

        # Δ_rank from D=0 tree
        dr = _delta_rank_from_tree(trees[0])
        if dr != float("inf"):
            delta_rank_steps.append(dr)

        # Advance with D=min(1, max_depth) tree-best
        best_D = min(1, args.max_depth)
        chosen = trees[best_D].tree_best_action
        if not chosen:
            break
        next_ctx, _, _ = evaluator._transition(context, chosen)
        context = next_ctx
        log.info("PILOT step %d/%d: chosen=%s feasible=%s",
                 t + 1, args.pilot_steps, chosen, context.current_state.get("is_feasible"))

    mean_delta_rank = statistics.mean(delta_rank_steps) if delta_rank_steps else 0.0
    per_depth: dict[int, dict] = {}
    for D in range(args.max_depth):
        sg_list = sigma_g_per_depth[D]
        mean_sg = statistics.mean(sg_list) if sg_list else 0.0
        threshold = 2.0 * (gamma ** (D + 1)) * mean_sg
        reliable_fraction = (
            sum(1 for dr in delta_rank_steps if dr > threshold) / len(delta_rank_steps)
            if delta_rank_steps else 0.0
        )
        per_depth[D] = {
            "sigma_g_mean": mean_sg,
            "sigma_g_std": _std_safe(sg_list),
            "threshold": threshold,
            "reliable_fraction": reliable_fraction,
        }
        log.info("PILOT D=%d: σ_G=%.4f threshold=%.4f reliable=%.1f%%",
                 D, mean_sg, threshold, reliable_fraction * 100)

    recommended_D = next(
        (D for D in range(args.max_depth + 1)
         if per_depth.get(D, {}).get("reliable_fraction", 0.0) >= args.reliability_target),
        args.max_depth,
    )
    log.info("PILOT: Δ_rank_mean=%.4f  recommended_D=%d  (target reliable=%.0f%%)",
             mean_delta_rank, recommended_D, args.reliability_target * 100)
    return {
        "recommended_D": recommended_D,
        "mean_delta_rank": mean_delta_rank,
        "per_depth": per_depth,
        "pilot_steps_run": len(delta_rank_steps),
        "had_candidates": True,
    }


# ── Adaptive depth convergence (§3.3) ─────────────────────────────────────────

def expand_until_reliable(
    evaluator,
    context,
    candidates,
    *,
    D_start: int,
    D_max: int,
    gamma: float,
    b1: int,
    bd: int,
) -> tuple:
    """
    Expand tree depth until §3.3 condition is satisfied or budget exhausted.

    Always runs D_start and D_start+1 to get initial σ_G estimate,
    then continues expanding if condition is not met.

    Returns: (tree, depth_used, sigma_g, delta_rank, n_expansions, dg_per_cand)
    """
    tree_D = _run_tree(evaluator, context, candidates, D_start, b1, bd, gamma)
    n_expansions = 0

    if D_start >= D_max:
        dr = _delta_rank_from_tree(tree_D)
        return tree_D, D_start, 0.0, dr, 0, []

    # Always run D_start+1 to get σ_G
    tree_D1 = _run_tree(evaluator, context, candidates, D_start + 1, b1, bd, gamma)
    n_expansions = 1

    dg = _delta_g_per_candidate(tree_D, tree_D1)
    sigma_g = _std_safe(dg)
    dr = _delta_rank_from_tree(tree_D1)
    threshold = 2.0 * (gamma ** (D_start + 2)) * sigma_g

    if dr >= threshold or (D_start + 1) >= D_max:
        return tree_D1, D_start + 1, sigma_g, dr, n_expansions, dg

    # Continue expanding
    prev_tree = tree_D1
    for current_depth in range(D_start + 2, D_max + 1):
        # Check if all candidates same class — no new info
        classes = {cand.candidate.cls for cand in prev_tree.evaluated if cand.candidate.cls}
        if len(classes) <= 1:
            break

        tree = _run_tree(evaluator, context, candidates, current_depth, b1, bd, gamma)
        n_expansions += 1

        dg = _delta_g_per_candidate(prev_tree, tree)
        sigma_g = _std_safe(dg)
        dr = _delta_rank_from_tree(tree)
        threshold = 2.0 * (gamma ** (current_depth + 1)) * sigma_g

        if dr >= threshold:
            return tree, current_depth, sigma_g, dr, n_expansions, dg

        prev_tree = tree

    # Budget exhausted — return deepest tree
    dr = _delta_rank_from_tree(prev_tree)
    return prev_tree, D_max, sigma_g, dr, n_expansions, dg


# ── Phase 2: MCTS episode ──────────────────────────────────────────────────────

def run_mcts_episode(
    evaluator,
    problem_spec: dict,
    ablation: dict,
    pilot: dict,
    args,
    wandb_io_table,
    llm_io_path: Optional[Path],
) -> Optional[MCTSEpisodeRecord]:
    """Run a full H-step MCTS episode under one ablation config."""
    from llm_finetune.training.rl.posterior.features import action_class
    from llm_finetune.training.rl.posterior.potential import compute_potential
    from llm_finetune.training.rl.posterior.tree_expansion import class_entropy

    akey = ablation["label"]
    D = ablation["D"]
    b1 = ablation.get("b1", args.level1_branching)
    K = ablation["K"]
    adaptive = ablation["adaptive"]
    entropy_threshold = ablation.get("entropy_threshold", 0.0)
    gamma = args.gamma
    alpha = args.alpha
    problem_id = problem_spec.get("problem_id", "unknown")

    log.info("EPISODE start: %s  problem=%s", akey, problem_id)
    if hasattr(evaluator, "configure_generation_logging"):
        evaluator.configure_generation_logging(ablation_key=akey)

    context = evaluator._initial_context(problem_spec)
    if context is None:
        log.warning("EPISODE: failed to init context for %s", problem_id)
        return None

    initial_mass = float(context.initial_state.get("mass", 1.0) or 1.0)
    phi_initial = compute_potential(
        context.current_state,
        initial_mass=initial_mass,
        alpha=alpha,
    )
    mass_initial = float(context.current_state.get("mass", 0.0) or 0.0)

    step_records: list[MCTSStepRecord] = []
    total_fea = 0
    n_adaptive_exp = 0
    n_entropy_gated = 0
    started_at = time.perf_counter()

    from llm_finetune.training.rl.posterior.online_search_policy import OnlineSearchPolicy, LLMCodeOptimizer

    delta_g_bar = 0.0
    if pilot.get("per_depth"):
        bars = [v.get("sigma_g_mean", 0.0) for v in pilot["per_depth"].values()]
        delta_g_bar = statistics.mean(bars) if bars else 0.0

    policy = OnlineSearchPolicy(gamma=gamma, rho_window=3, rho_threshold=0.85, delta_g_bar=delta_g_bar)
    optimizer = LLMCodeOptimizer(rho_window=3, rho_threshold=0.85)
    optimizer_triggered = False
    optimizer_fea_calls = 0
    optimizer_code_str = ""
    optimizer_phi_gain_val = 0.0

    for t in range(args.max_steps):
        step_start = time.perf_counter()

        if hasattr(evaluator, "configure_generation_logging"):
            evaluator.configure_generation_logging(ablation_key=akey, step_t=t)

        # Generate K LLM candidates
        messages = context.build_messages(evaluator.formatter)
        candidates, top_action, attempts = evaluator.generate_candidates(
            context,
            num_candidates=K,
            include_greedy=True,
            stage_label=f"{akey} step {t}",
        )
        _log_llm_io(wandb_io_table, None, problem_id, akey, t, attempts, messages)

        if not candidates:
            log.warning("EPISODE %s step %d: no candidates, stopping", akey, t)
            break

        top_class = action_class(top_action) if top_action else ""
        candidates_raw = [c.metadata.get("raw_text", "") if c.metadata else "" for c in candidates]
        candidates_parsed = [c.action or "" for c in candidates]
        candidates_classes = [c.cls or "" for c in candidates]
        parse_ok = sum(1 for c in candidates if c.action)

        phi_before = compute_potential(
            context.current_state,
            initial_mass=initial_mass,
            alpha=alpha,
        )
        class_coverage = len({c.cls for c in candidates if c.cls})
        cand_ent = class_entropy(candidates) if candidates else 0.0
        step_entropy_gated = False

        # ---- Tree evaluation (transition deferred to after OSP decisions) ----
        if D == 0 and not adaptive:
            chosen = top_action or (candidates[0].action if candidates else "")
            tree = None
            depth_used = 0
            sigma_g = 0.0
            dr = 0.0
            threshold_33 = 0.0
            reliable = True
            dg_per_cand: list[float] = []
            n_exp = 0
        elif adaptive and entropy_threshold > 0.0 and cand_ent < entropy_threshold:
            chosen = top_action or (candidates[0].action if candidates else "")
            tree = None
            depth_used = 0
            sigma_g = 0.0
            dr = 0.0
            threshold_33 = 0.0
            reliable = True
            dg_per_cand = []
            n_exp = 0
            step_entropy_gated = True
            n_entropy_gated += 1
        elif adaptive:
            tree, depth_used, sigma_g, dr, n_exp, dg_per_cand = expand_until_reliable(
                evaluator, context, candidates,
                D_start=max(D, 1), D_max=args.max_depth,
                gamma=gamma, b1=b1, bd=args.deeper_branching,
            )
            threshold_33 = 2.0 * (gamma ** (depth_used + 1)) * sigma_g
            reliable = dr >= threshold_33
            n_adaptive_exp += n_exp
            chosen = tree.tree_best_action or (candidates[0].action if candidates else "")
        else:
            tree = _run_tree(evaluator, context, candidates, D, b1, args.deeper_branching, gamma)
            chosen = tree.tree_best_action or (candidates[0].action if candidates else "")
            depth_used = D
            sigma_g = 0.0
            dr = _delta_rank_from_tree(tree)
            threshold_33 = 0.0
            reliable = True
            dg_per_cand = []
            n_exp = 0

        if not chosen:
            log.warning("EPISODE %s step %d: no valid action chosen, stopping", akey, t)
            break

        # ---- Online Search Policy decisions ----
        step_backtracked = False
        bt_ctx = None
        if tree is not None:
            V_hat = tree.baseline if tree.evaluated else 0.0

            # Decision 1: Diversity injection when §3.3 ranking condition is unmet
            if policy.should_diversify(dr, depth_used, sigma_g):
                div_suffix = policy.diversity_prompt_suffix(candidates)
                div_cands, _, _ = evaluator.generate_candidates(
                    context,
                    num_candidates=K,
                    include_greedy=False,
                    stage_label=f"{akey} step {t} diversity",
                    prompt_suffix=div_suffix,
                )
                seen_actions = {c.action for c in candidates}
                for nc in div_cands:
                    if nc.action and nc.action not in seen_actions:
                        candidates.append(nc)
                        seen_actions.add(nc.action)
                tree = _run_tree(evaluator, context, candidates, depth_used, b1, args.deeper_branching, gamma)
                dr = _delta_rank_from_tree(tree)
                chosen = tree.tree_best_action or chosen
                V_hat = tree.baseline if tree.evaluated else V_hat

            rho_step = int(top_action == chosen) if top_action else 0
            policy.update(context=context, V_hat=V_hat, rho=rho_step)

            # Decision 2: §3.2 Branch-and-bound backtrack
            should_bt, bt_ctx = policy.check_backtrack(V_hat, depth_used)
            if should_bt and bt_ctx is not None:
                step_backtracked = True

        # Decision 3: LLM optimizer handoff when ρ has converged
        if policy.should_optimize() and not optimizer_triggered:
            rho_mean_recent = (
                statistics.mean(r.rho for r in step_records[-policy.rho_window:])
                if len(step_records) >= policy.rho_window else 0.0
            )
            opt_budget = max(1, args.max_steps - t)
            opt_ctx, opt_code, opt_calls = optimizer.run(context, evaluator, opt_budget, rho_mean_recent)
            phi_after_opt = compute_potential(opt_ctx.current_state, initial_mass=initial_mass, alpha=alpha)
            optimizer_triggered = True
            optimizer_fea_calls = opt_calls
            optimizer_code_str = opt_code
            optimizer_phi_gain_val = phi_after_opt - phi_before
            total_fea += opt_calls
            context = opt_ctx
            log.info(
                "OSP optimizer: rho=%.2f fea=%d Φ_gain=%.4f feasible=%s",
                rho_mean_recent, opt_calls, optimizer_phi_gain_val,
                context.current_state.get("is_feasible", False),
            )
            break

        # ---- Transition ----
        chosen_class = action_class(chosen) if chosen else ""
        rho = int(top_action == chosen) if top_action else 0

        if step_backtracked and bt_ctx is not None:
            # Restore best context, no FEA transition this step
            context = bt_ctx
            next_ctx = bt_ctx
            reward = 0.0
            fea_calls = 0
        else:
            next_ctx, reward, fea_calls = evaluator._transition(context, chosen)

        phi_after = compute_potential(
            next_ctx.current_state,
            initial_mass=initial_mass,
            alpha=alpha,
        )
        if hasattr(evaluator, "log_mcts_decision"):
            tree_trace = getattr(tree, "trace", None) if tree is not None else None
            tree_best_action = getattr(tree, "tree_best_action", "") if tree is not None else ""
            evaluator.log_mcts_decision(
                problem_id=problem_id,
                ablation_key=akey,
                step_t=t,
                selected_action=chosen,
                selected_source="mcts_tree_best" if tree is not None else "llm_top1_no_tree",
                top_model_action=top_action or "",
                tree_best_action=tree_best_action or "",
                candidate_actions=candidates_parsed,
                actual_action_history=list(context.action_history),
                phi_before=phi_before,
                phi_after=phi_after,
                reward=reward,
                tree_trace=tree_trace,
            )

        # Estimate total FEA for this step
        step_fea = fea_calls
        if tree is not None:
            step_fea += tree.total_fea_calls
        total_fea += step_fea
        elapsed_s = time.perf_counter() - step_start

        rec = MCTSStepRecord(
            problem_id=problem_id, ablation_key=akey, t=t,
            depth_used=depth_used, delta_rank=dr, sigma_g=sigma_g,
            threshold_33=threshold_33, ranking_reliable=reliable,
            n_depth_expansions=n_exp,
            delta_g_per_candidate=dg_per_cand,
            delta_g_mean=statistics.mean(dg_per_cand) if dg_per_cand else 0.0,
            class_coverage=class_coverage,
            rho=rho, top_model_action=top_action or "", top_model_class=top_class,
            chosen_action=chosen, chosen_class=chosen_class,
            phi_before=phi_before, phi_after=phi_after, step_reward=reward,
            n_fea_calls=step_fea, elapsed_s=elapsed_s,
            prompt_last_user_message=(messages[-1]["content"][:400]
                                      if messages and messages[-1].get("role") == "user" else ""),
            candidates_raw=candidates_raw, candidates_parsed=candidates_parsed,
            candidates_classes=candidates_classes, parse_success_count=parse_ok,
            candidate_entropy=cand_ent, entropy_gated=step_entropy_gated,
            backtrack_triggered=step_backtracked,
        )
        step_records.append(rec)

        try:
            import wandb
            wandb.log({
                f"mcts/{akey}/step": t,
                f"mcts/{akey}/phi": phi_after,
                f"mcts/{akey}/rho": rho,
                f"mcts/{akey}/delta_rank": dr,
                f"mcts/{akey}/sigma_g": sigma_g,
                f"mcts/{akey}/depth_used": depth_used,
                f"mcts/{akey}/fea_calls": step_fea,
                f"mcts/{akey}/ranking_reliable": int(reliable),
                f"mcts/{akey}/candidate_entropy": cand_ent,
                f"mcts/{akey}/entropy_gated": int(step_entropy_gated),
            })
        except Exception:
            pass

        log.info(
            "EPISODE %s step %d/%d: chosen=%s rho=%d Δ_rank=%.3f σ_G=%.3f "
            "reliable=%s D_used=%d fea=%d Φ=%.4f H_ent=%.3f ent_gated=%s feasible=%s",
            akey, t + 1, args.max_steps, chosen_class, rho, dr, sigma_g,
            reliable, depth_used, step_fea, phi_after,
            cand_ent, step_entropy_gated,
            next_ctx.current_state.get("is_feasible", False),
        )

        context = next_ctx
        if context.current_state.get("is_feasible", False):
            log.info("EPISODE %s: feasible at step %d", akey, t + 1)
            break

    # Build episode record
    final_state = context.current_state
    phi_final = compute_potential(
        final_state,
        initial_mass=initial_mass,
        alpha=alpha,
    )
    mass_final = float(final_state.get("mass", 0.0) or 0.0)
    fos_b = float(final_state.get("fos_buckling", 0.0) or 0.0)
    fos_y = float(final_state.get("fos_yielding", 0.0) or 0.0)
    fos_min = min(fos_b, fos_y) if fos_b and fos_y else 0.0
    mass_red = (1.0 - mass_final / mass_initial) * 100.0 if mass_initial > 0 else 0.0

    delta_g_all = [v for r in step_records for v in r.delta_g_per_candidate]
    sigma_g_vals = [r.sigma_g for r in step_records if r.sigma_g > 0]

    ep = MCTSEpisodeRecord(
        problem_id=problem_id, ablation_key=akey, depth=D,
        level1_branching=b1, candidate_count=K, adaptive=adaptive,
        n_steps=len(step_records),
        phi_initial=phi_initial, phi_final=phi_final, phi_gain=phi_final - phi_initial,
        feasible=bool(final_state.get("is_feasible", False)),
        mass_initial=mass_initial, mass_final=mass_final, mass_reduction_pct=mass_red,
        fos_b_final=fos_b, fos_y_final=fos_y, fos_min_final=fos_min,
        delta_g_mean=statistics.mean(delta_g_all) if delta_g_all else 0.0,
        delta_g_max=max(delta_g_all) if delta_g_all else 0.0,
        sigma_g_mean=statistics.mean(sigma_g_vals) if sigma_g_vals else 0.0,
        ranking_reliable_fraction=sum(r.ranking_reliable for r in step_records) / max(len(step_records), 1),
        rho_mean=sum(r.rho for r in step_records) / max(len(step_records), 1),
        class_coverage_mean=sum(r.class_coverage for r in step_records) / max(len(step_records), 1),
        n_adaptive_expansions=n_adaptive_exp,
        entropy_gated_steps=n_entropy_gated,
        candidate_entropy_mean=statistics.mean(r.candidate_entropy for r in step_records) if step_records else 0.0,
        n_backtracks=policy.n_backtracks,
        optimizer_triggered=optimizer_triggered,
        optimizer_fea_calls=optimizer_fea_calls,
        optimizer_phi_gain=optimizer_phi_gain_val,
        optimizer_code=optimizer_code_str,
        total_fea_calls=total_fea,
        total_elapsed_s=time.perf_counter() - started_at,
        steps=[asdict(r) for r in step_records],
    )

    try:
        import wandb
        wandb.log({
            f"mcts/episode/{akey}/phi_gain": ep.phi_gain,
            f"mcts/episode/{akey}/feasible": int(ep.feasible),
            f"mcts/episode/{akey}/rho_mean": ep.rho_mean,
            f"mcts/episode/{akey}/delta_g_mean": ep.delta_g_mean,
            f"mcts/episode/{akey}/sigma_g_mean": ep.sigma_g_mean,
            f"mcts/episode/{akey}/total_fea": ep.total_fea_calls,
            f"mcts/episode/{akey}/mass_reduction_pct": ep.mass_reduction_pct,
            f"mcts/episode/{akey}/entropy_gated_steps": ep.entropy_gated_steps,
            f"mcts/episode/{akey}/candidate_entropy_mean": ep.candidate_entropy_mean,
        })
    except Exception:
        pass

    log.info(
        "EPISODE %s done: Φ_gain=%.4f feasible=%s mass_red=%.1f%% "
        "rho=%.3f δ_G=%.4f σ_G=%.4f rel=%.1f%% fea=%d t=%.1fs",
        akey, ep.phi_gain, ep.feasible, mass_red,
        ep.rho_mean, ep.delta_g_mean, ep.sigma_g_mean,
        ep.ranking_reliable_fraction * 100, total_fea, ep.total_elapsed_s,
    )
    return ep


