AIRFOIL_VERBS = (
    VerbSpec("MOVE_CTRL_POINT", (ArgSpec("k", "int", "control point 0..K-1 (0 = trailing edge on the "
                                                      "upper surface, K/2 = leading edge, K-1 = trailing "
                                                      "edge on the lower surface)"),
                                 ArgSpec("dx", "float", "chord fractions, |dx| <= 0.03"),
                                 ArgSpec("dy", "float", "chord fractions, |dy| <= 0.03")),
             "move one control point of the closed cubic B-spline; the C2 surface follows",
             phrase="Move a control point"),
    VerbSpec("THICKEN", (ArgSpec("span", "str", "fore | mid | aft (chord thirds)"),
                         ArgSpec("pct", "float", "-30 .. 30 percent")),
             "scale the thickness (upper minus lower surface about the camber line) of the control "
             "points in that span by pct percent", phrase="Thicken a span"),
    VerbSpec("CAMBER", (ArgSpec("span", "str", "fore | mid | aft"),
                        ArgSpec("pct", "float", "-3 .. 3 percent of chord")),
             "raise (positive) or lower the camber line in that span by pct percent of chord, upper "
             "and lower surfaces moving together", phrase="Camber a span"),
)

K_CTRL = 16          # control points: K/2 per surface, shared x stations, closed at the trailing edge
N_PTS = 192          # EngiBench airfoil coordinate count


def _bspline_closed(P: np.ndarray, n: int) -> np.ndarray:
    """Closed uniform cubic B-spline through control polygon P (K, 2) sampled at
    n parameter values -> (2, n) coordinates (EngiBench's coords layout)."""
    K = P.shape[0]
    t = np.linspace(0.0, K, n, endpoint=False)
    i = np.floor(t).astype(int)
    u = t - i
    b0 = (1 - u) ** 3 / 6.0
    b1 = (3 * u ** 3 - 6 * u ** 2 + 4) / 6.0
    b2 = (-3 * u ** 3 + 3 * u ** 2 + 3 * u + 1) / 6.0
    b3 = u ** 3 / 6.0
    pts = (b0[:, None] * P[(i - 1) % K] + b1[:, None] * P[i % K]
           + b2[:, None] * P[(i + 1) % K] + b3[:, None] * P[(i + 2) % K])
    return pts.T


def _self_intersects(curve: np.ndarray) -> bool:
    """EngiBench's does_not_self_intersect rule (its own routine when importable)."""
    try:
        from engibench.problems.airfoil.v0 import self_intersect
        return self_intersect(np.asarray(curve, dtype=float)) is not None
    except Exception:
        seg = curve[1:] - curve[:-1]
        n = seg.shape[0]
        for i in range(n - 1):
            p, dp = curve[i], seg[i]
            end = n - 1 if i == 0 else n
            q, dq = curve[i + 2:end], seg[i + 2:end]
            x = np.cross(dp, dq)
            ok = x != 0
            if not ok.any():
                continue
            t = np.cross(q[ok] - p, dq[ok]) / x[ok]
            s = np.cross(q[ok] - p, dp) / x[ok]
            if np.any((t >= 0) & (t <= 1) & (s >= 0) & (s <= 1)):
                return True
        return False


class AirfoilStubDomain(Domain):
    """EngiBench Airfoil (MACH-Aero, 2-D RANS at Mach 0.8, Re 1e6; objective cd, lift
    coefficient cl >= cl_target, area >= area_ratio_min x the initial area) with the
    shape verbs MOVE_CTRL_POINT / THICKEN / CAMBER on a closed cubic B-spline of
    K_CTRL control points (K/2 per surface at shared chord stations, trailing edge
    at x = 1, leading edge at x = 0). Validity (spline continuity): the control
    points of each surface keep strictly monotone x (no fold-over, so the C2
    spline stays a single-valued surface), the upper surface stays above the
    lower one at every station, every coordinate stays in [0, 1], and the sampled
    192-point curve does not self-intersect (EngiBench's own check).
    STUB: evaluate() raises NotImplementedError - the simulator is a docker
    container (mdolab/public:u22-gcc-ompi-stable) absent on Windows and drc. It is
    not registered and make_problem of EngiBenchDomain never yields it."""

    name = "engibench_airfoil_stub"
    native_moves = True
    verbs = AIRFOIL_VERBS
    reference_class = "heuristic"

    def make_problem(self, index: int, rng: np.random.Generator) -> dict:
        # a NACA 4-digit base shape with random camber/thickness, as control points
        mcam = float(rng.uniform(0.0, 0.04))
        pcam = float(rng.uniform(0.3, 0.5))
        tmax = float(rng.uniform(0.09, 0.15))
        half = K_CTRL // 2
        xs = 0.5 * (1 - np.cos(np.linspace(0, math.pi, half + 1)))[1:]   # (0, 1], LE excluded
        xs = xs[::-1]                                                      # TE -> LE

        def yc(x):
            return np.where(x < pcam, mcam / pcam ** 2 * (2 * pcam * x - x ** 2),
                            mcam / (1 - pcam) ** 2 * (1 - 2 * pcam + 2 * pcam * x - x ** 2))

        def yt(x):
            return 5 * tmax * (0.2969 * np.sqrt(x) - 0.126 * x - 0.3516 * x ** 2
                               + 0.2843 * x ** 3 - 0.1036 * x ** 4)
        up = np.stack([xs, yc(xs) + yt(xs)], axis=1)
        lo = np.stack([xs[::-1], yc(xs[::-1]) - yt(xs[::-1])], axis=1)
        P = np.concatenate([up, [[0.0, 0.0]], lo[:-1]])[:K_CTRL]
        P[:, 1] += 0.5 - float(np.mean(P[:, 1]))     # EngiBench coords live in [0, 1]
        return {"family": "airfoil", "control_points": P.tolist(), "mach": 0.8, "reynolds": 1e6,
                "angle_of_attack": float(rng.uniform(1.0, 3.0)), "cl_target": 0.5,
                "area_ratio_min": 0.7, "area_initial": float(self._area(_bspline_closed(P, N_PTS))),
                "goals": {"minimum_cl": 0.5, "minimum_area_ratio": 0.7},
                "simulator": "UNAVAILABLE: MACH-Aero/ADflow RANS in docker (stub)"}

    @staticmethod
    def _area(coords: np.ndarray) -> float:
        x, y = coords
        return 0.5 * abs(float(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))

    def load(self, spec):
        return {"P": np.asarray(spec["control_points"], dtype=float), "spec": spec}

    def clone(self, st):
        return {"P": st["P"].copy(), "spec": st["spec"]}

    def coords(self, st) -> np.ndarray:
        return _bspline_closed(st["P"], N_PTS)

    def valid(self, st) -> Tuple[bool, str]:
        P = st["P"]
        half = K_CTRL // 2
        up, lo = P[:half], P[half + 1:]
        if np.any(np.diff(up[:, 0]) >= 0):
            return False, "upper-surface control points fold back in x (spline continuity)"
        if np.any(np.diff(lo[:, 0]) <= 0):
            return False, "lower-surface control points fold back in x (spline continuity)"
        if np.any(up[:, 1][::-1][: len(lo)] < lo[:, 1][: len(up)]):
            return False, "upper surface below the lower surface"
        c = self.coords(st)
        if c.min() < 0.0 or c.max() > 1.0:
            return False, "coordinates leave the unit box"
        if _self_intersects(c.T):
            return False, "curve self-intersects"
        return True, ""

    def evaluate(self, st, seed: int = 0) -> dict:
        raise NotImplementedError(
            "EngiBench airfoil simulator unavailable: MACH-Aero (ADflow RANS, Mach 0.8) runs in the "
            "docker image mdolab/public:u22-gcc-ompi-stable; no container runtime on Windows or drc.")

    def legal_moves(self, st, rng, max_candidates=None) -> List[Move]:
        out: List[Move] = []
        for k in range(K_CTRL):
            for dx, dy in ((0.0, 0.01), (0.0, -0.01), (0.01, 0.0), (-0.01, 0.0)):
                mv = Move("MOVE_CTRL_POINT", {"k": k, "dx": dx, "dy": dy})
                if self._admissible(st, mv):
                    out.append(mv)
        for span in ("fore", "mid", "aft"):
            for pct in (-10.0, 10.0):
                mv = Move("THICKEN", {"span": span, "pct": pct})
                if self._admissible(st, mv):
                    out.append(mv)
            for pct in (-0.5, 0.5):
                mv = Move("CAMBER", {"span": span, "pct": pct})
                if self._admissible(st, mv):
                    out.append(mv)
        return self.subsample_moves(out, rng, max_candidates)

    def _admissible(self, st, mv) -> bool:
        trial = self.clone(st)
        try:
            self.apply(trial, mv)
        except ValueError:
            return False
        return True

    def apply(self, st, move: Move) -> None:
        P = st["P"]
        half = K_CTRL // 2
        a = move.args
        if move.verb == "MOVE_CTRL_POINT":
            k, dx, dy = int(a["k"]), float(a["dx"]), float(a["dy"])
            if not (0 <= k < K_CTRL) or abs(dx) > 0.03 or abs(dy) > 0.03 or (dx == 0 and dy == 0):
                raise ValueError("MOVE_CTRL_POINT: k in 0..%d, 0 < |dx|,|dy| <= 0.03" % (K_CTRL - 1))
            P[k, 0] += dx
            P[k, 1] += dy
        elif move.verb in ("THICKEN", "CAMBER"):
            span, pct = str(a["span"]), float(a["pct"])
            lo_x, hi_x = {"fore": (0.0, 1 / 3), "mid": (1 / 3, 2 / 3), "aft": (2 / 3, 1.01)}.get(span, (None, None))
            if lo_x is None:
                raise ValueError("span must be fore, mid or aft")
            lim = 30.0 if move.verb == "THICKEN" else 3.0
            if not (0 < abs(pct) <= lim):
                raise ValueError("%s: 0 < |pct| <= %g" % (move.verb, lim))
            for i in range(half):
                j = K_CTRL - 1 - i              # the lower-surface point at the same station
                if j <= half:
                    continue
                x = P[i, 0]
                if not (lo_x <= x < hi_x):
                    continue
                c = 0.5 * (P[i, 1] + P[j, 1])
                t = P[i, 1] - P[j, 1]
                if move.verb == "THICKEN":
                    t *= 1.0 + pct / 100.0
                else:
                    c += pct / 100.0
                P[i, 1], P[j, 1] = c + t / 2, c - t / 2
        else:
            raise ValueError("airfoil has no verb %r" % move.verb)
        ok, why = self.valid(st)
        if not ok:
            raise ValueError("invalid airfoil after %s: %s" % (self.format_move(move), why))

    def program(self, spec) -> DesignProgram:
        prog = program_from_goals(spec["goals"], objective_key="cd", objective_sense="min",
                                  domain=self.name)
        return replace(prog, validity_bounds=(("cd", 1.0), ("cl", 5.0)))

    def describe(self, st, spec) -> str:
        c = self.coords(st)
        return ("PROBLEM\nAirfoil shape design (EngiBench Airfoil, MACH-Aero 2-D RANS at Mach %s, "
                "Reynolds %s, angle of attack %s deg): minimise the drag coefficient cd with lift "
                "coefficient cl >= %s and area >= %s x the initial area %s. The shape is a closed "
                "cubic B-spline of %d control points (k = 0 trailing edge, upper surface towards "
                "the leading edge k = %d, then the lower surface back to the trailing edge). "
                "Verbs move one control point, or scale thickness / shift camber over a chord "
                "third. SIMULATOR UNAVAILABLE (stub).\nDESIGN\ncontrol points (x, y): %s\narea %s"
                % (spec["mach"], spec["reynolds"], spec["angle_of_attack"], spec["cl_target"],
                   spec["area_ratio_min"], _num(spec["area_initial"], 4), K_CTRL, K_CTRL // 2,
                   "; ".join("%d:(%s, %s)" % (k, _num(x, 4), _num(y, 4)) for k, (x, y) in enumerate(st["P"])),
                   _num(self._area(c), 4)))


# ── number formatting (as the other domains: 3 significant figures) ──────────
def _num(x, sig: int = 3) -> str:
    try:
        x = float(x)
    except (TypeError, ValueError):
        return str(x)
    if not math.isfinite(x):
        return "inf" if x > 0 else ("-inf" if x < 0 else "nan")
    if x == 0.0:
        return "0"
    if abs(x) < 1e-4:
        mant, ex = ("%.*e" % (max(sig - 1, 0), x)).split("e")
        if "." in mant:
            mant = mant.rstrip("0").rstrip(".")
        return "%se%d" % (mant, int(ex))
    mag = int(math.floor(math.log10(abs(x))))
    dec = max(0, sig - 1 - mag)
    s = "%.*f" % (dec, x)
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return "0" if s in ("", "-0") else s
