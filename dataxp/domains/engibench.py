    def n_elements(self, st) -> int:
        raise NotImplementedError("engibench addresses the field with region verbs, not elements")

    def get(self, st, i, p):
        return None

    def set(self, st, i, p, v):
        raise ValueError("engibench has no SET_PARAM")

    def bounds(self, st, p):
        return (0.0, 0.0)

    # ── moves ───────────────────────────────────────────────────────────────
    def grammar(self) -> str:
        head = ("The design is a solid/void field of W columns x H rows (W, H given in the "
                "observation). x = column index 0..W-1 left to right, y = row index 0..H-1 top "
                "to bottom; a cell is (x, y). k = the label of a connected component (solid "
                "cells joined through shared edges), as numbered in the observation's component "
                "list (largest first; labels are recomputed after every change). %s must "
                "change at least one cell."
                % ("A verb" if spelled_in_verbs(self) else "An operation"))
        return head + "\n" + Domain.grammar(self)

    def legal_moves(self, st, rng: np.random.Generator,
                    max_candidates: Optional[int] = None) -> List[Move]:
        an = self._analysis(st)
        rho = st["rho"]
        H, W = rho.shape
        S = an["proxy"]
        labels, comps = an["labels"], an["comps"]
        solid = rho > 0
        void = ~solid
        out: List[Move] = []
        # component moves
        for k, c in enumerate(comps[:N_COMP_MOVES]):
            out.append(Move("DILATE", {"k": k, "px": 1}))
            if c["size"] >= 40:
                out.append(Move("DILATE", {"k": k, "px": 2}))
            mask = labels == k
            if ndimage.binary_erosion(mask, structure=_STRUCT8, border_value=1).any():
                out.append(Move("ERODE", {"k": k, "px": 1}))
        n_shift = 0
        for k, c in enumerate(comps):
            if n_shift >= N_SHIFT_COMPS:
                break
            if c["size"] > 0.15 * H * W:
                continue
            n_shift += 1
            for dx, dy in ((3, 0), (-3, 0), (0, 3), (0, -3)):
                if self._shift_ok(labels == k, dx, dy):
                    out.append(Move("SHIFT_FEATURE", {"k": k, "dx": dx, "dy": dy}))
        # fill where the field works hardest across void
        for y, x in _nms_spots(S, void, N_SPOTS, 5):
            for r in (2.0, 4.0):
                out.append(Move("FILL_DISK", {"cx": int(x), "cy": int(y), "r": r}))
        for y, x in _nms_spots(S, void, 2, 8):
            for w, h in ((9, 2), (2, 9)):
                x0, y0 = int(max(0, min(x - w // 2, W - w))), int(max(0, min(y - h // 2, H - h)))
                mv = Move("FILL_RECT", {"x0": x0, "y0": y0, "x1": x0 + w - 1, "y1": y0 + h - 1})
                if self._rect_changes(rho, mv, 1):
                    out.append(mv)
        out += self._bridges(rho, labels, comps)
        # clear where solid material carries least
        if solid.any():
            for y, x in _nms_spots(-S, solid, N_SPOTS, 5):
                for r in (2.0, 3.0):
                    out.append(Move("CLEAR_DISK", {"cx": int(x), "cy": int(y), "r": r}))
            for y, x in _nms_spots(-S, solid, 2, 8):
                for w, h in ((7, 2), (2, 7)):
                    x0, y0 = int(max(0, min(x - w // 2, W - w))), int(max(0, min(y - h // 2, H - h)))
                    mv = Move("CLEAR_RECT", {"x0": x0, "y0": y0, "x1": x0 + w - 1, "y1": y0 + h - 1})
                    if self._rect_changes(rho, mv, 0):
                        out.append(mv)
        # a few random spots (rng-driven, so the set is not a pure function of S)
        vc = np.argwhere(void)
        for _ in range(2):
            if len(vc):
                y, x = vc[int(rng.integers(len(vc)))]
                out.append(Move("FILL_DISK", {"cx": int(x), "cy": int(y), "r": 3.0}))
        sc = np.argwhere(solid)
        for _ in range(2):
            if len(sc):
                y, x = sc[int(rng.integers(len(sc)))]
                out.append(Move("CLEAR_DISK", {"cx": int(x), "cy": int(y), "r": 2.0}))
        # dedupe (stable)
        seen = set()
        uniq = []
        for mv in out:
            key = self.format_move(mv)
            if key not in seen:
                seen.add(key)
                uniq.append(mv)
        cap = MAX_CANDS[st["fx"]["family"]]
        if max_candidates is not None:
            cap = min(cap, int(max_candidates))
        # one count, two pools (docstring "CANDIDATE OFFER RULE"): n is what the
        # structured pool offered alone; ceil(n/4) slots go to the exploration
        # sample across the full advertised ranges, the rest to a stable
        # subsample of the structured pool
        n_total = min(cap, len(uniq))
        n_explore = int(math.ceil(EXPLORE_FRAC * n_total))
        explore = self._explore_sample(st, rng, n_explore, seen)
        structured = self.subsample_moves(uniq, rng, n_total - len(explore))
        return structured + explore

    def _explore_sample(self, st, rng: np.random.Generator, n: int, taken: set) -> List[Move]:
        """n moves drawn across the FULL advertised argument ranges (the
        exploration half of the offer rule). Verbs in round-robin order
        EXPLORE_VERBS from a random offset; a disk is centred on a uniformly
        random void (FILL) / solid (CLEAR) cell with an integer radius uniform in
        R_MIN..R_MAX; a rectangle has sides log-uniform in 1..W / 1..H and is
        placed uniformly around a random void / solid anchor cell that stays
        inside it (clipped to the field); SHIFT_FEATURE takes k uniform over the
        components the observation lists (the LISTED_COMPS largest) and dx, dy
        uniform in -SHIFT_MAX..SHIFT_MAX, not both 0; DILATE / ERODE take k the
        same way and px uniform in 1..DILATE_MAX / 1..ERODE_MAX. Every draw is
        checked with the tests apply() makes (changes a cell, keeps a cell on the
        field, does not delete the component); a refused draw or a duplicate of
        a move already offered (``taken``, format_move keys, updated in place)
        is redrawn, at most EXPLORE_TRIES_PER_SLOT draws per slot in all."""
        if n <= 0:
            return []
        an = self._analysis(st)
        rho = st["rho"]
        H, W = rho.shape
        labels, comps = an["labels"], an["comps"]
        void = np.argwhere(rho == 0)
        solid = np.argwhere(rho > 0)
        listed = min(LISTED_COMPS, len(comps))
        out: List[Move] = []
        offset = int(rng.integers(len(EXPLORE_VERBS)))
        tries = 0
        while len(out) < n and tries < EXPLORE_TRIES_PER_SLOT * n:
            verb = EXPLORE_VERBS[(offset + tries) % len(EXPLORE_VERBS)]
            tries += 1
            mv = self._explore_draw(verb, rng, rho, labels, listed, void, solid)
            if mv is None:
                continue
            key = self.format_move(mv)
            if key in taken:
                continue
            taken.add(key)
            out.append(mv)
        return out

    @staticmethod
    def _log_uniform_int(rng: np.random.Generator, hi: int) -> int:
        """Integer in 1..hi with P(v) proportional to 1/v (every side length of
        the field reachable, small ones most often)."""
        hi = max(1, int(hi))
        u = float(rng.random())
        return int(min(hi, max(1, math.floor(math.exp(u * math.log(hi + 1))))))

    def _explore_draw(self, verb: str, rng, rho, labels, listed: int, void, solid) -> Optional[Move]:
        H, W = rho.shape
        if verb in ("FILL_DISK", "FILL_RECT"):
            cells = void
        elif verb in ("CLEAR_DISK", "CLEAR_RECT"):
            cells = solid
        else:
            cells = None
        if cells is not None and not len(cells):
            return None
        if verb in ("FILL_DISK", "CLEAR_DISK"):
            y, x = cells[int(rng.integers(len(cells)))]
            r = float(rng.integers(int(R_MIN), int(R_MAX) + 1))
            return Move(verb, {"cx": int(x), "cy": int(y), "r": r})
        if verb in ("FILL_RECT", "CLEAR_RECT"):
            y, x = cells[int(rng.integers(len(cells)))]
            w = self._log_uniform_int(rng, W)
            h = self._log_uniform_int(rng, H)
            x0 = int(max(0, int(x) - int(rng.integers(w))))
            y0 = int(max(0, int(y) - int(rng.integers(h))))
            x1 = int(min(W - 1, x0 + w - 1))
            y1 = int(min(H - 1, y0 + h - 1))
            return Move(verb, {"x0": x0, "y0": y0, "x1": x1, "y1": y1})
        if listed <= 0:
            return None
        k = int(rng.integers(listed))
        mask = labels == k
        if verb == "SHIFT_FEATURE":
            dx = int(rng.integers(-SHIFT_MAX, SHIFT_MAX + 1))
            dy = int(rng.integers(-SHIFT_MAX, SHIFT_MAX + 1))
            if (dx == 0 and dy == 0) or not self._shift_ok(mask, dx, dy):
                return None
            return Move(verb, {"k": k, "dx": dx, "dy": dy})
        if verb == "DILATE":
            px = int(rng.integers(1, DILATE_MAX + 1))
            grown = ndimage.binary_dilation(mask, structure=_STRUCT8, iterations=px)
            if not (grown & (rho == 0)).any():
                return None
            return Move(verb, {"k": k, "px": px})
        px = int(rng.integers(1, ERODE_MAX + 1))
        kept = ndimage.binary_erosion(mask, structure=_STRUCT8, iterations=px, border_value=1)
        if not kept.any() or not (mask & ~kept).any():
            return None
        return Move(verb, {"k": k, "px": px})

    @staticmethod
    def _shift_ok(mask: np.ndarray, dx: int, dy: int) -> bool:
        H, W = mask.shape
        cells = np.argwhere(mask)
        if not len(cells):
            return False
        ny, nx = cells[:, 0] + dy, cells[:, 1] + dx
        return bool(np.any((ny >= 0) & (ny < H) & (nx >= 0) & (nx < W)))

    @staticmethod
    def _rect_changes(rho: np.ndarray, mv: Move, val: int) -> bool:
        a = mv.args
        sub = rho[a["y0"]:a["y1"] + 1, a["x0"]:a["x1"] + 1]
        return bool(np.any(sub != val))

    @staticmethod
    def _bridges(rho: np.ndarray, labels: np.ndarray, comps: List[dict], top: int = 4) -> List[Move]:
        """FILL_RECT candidates joining the closest cells of component pairs
        (bounding box of the two cells, at least 2 wide, area <= 80)."""
        out: List[Move] = []
        if len(comps) < 2:
            return out
        from scipy.spatial import cKDTree
        pts = []
        for k in range(min(top, len(comps))):
            mask = labels == k
            edge = mask & ~ndimage.binary_erosion(mask, structure=_STRUCT4, border_value=1)
            cells = np.argwhere(edge if edge.any() else mask)
            pts.append(cells)
        pairs = []
        for i in range(len(pts)):
            ti = cKDTree(pts[i])
            for j in range(i + 1, len(pts)):
                d, idx = ti.query(pts[j])
                m = int(np.argmin(d))
                pairs.append((float(d[m]), i, j, pts[i][idx[m]], pts[j][m]))
        pairs.sort(key=lambda t: (t[0], t[1], t[2]))
        H, W = rho.shape
        for d, i, j, a, b in pairs[:3]:
            y0, y1 = int(min(a[0], b[0])), int(max(a[0], b[0]))
            x0, x1 = int(min(a[1], b[1])), int(max(a[1], b[1]))
            if x1 - x0 < 1:
                x1 = min(W - 1, x0 + 1)
            if y1 - y0 < 1:
                y1 = min(H - 1, y0 + 1)
            if (x1 - x0 + 1) * (y1 - y0 + 1) > 80:
                continue
            mv = Move("FILL_RECT", {"x0": x0, "y0": y0, "x1": x1, "y1": y1})
            if EngiBenchDomain._rect_changes(rho, mv, 1):
                out.append(mv)
        return out

    def apply(self, st, move: Move) -> None:
        rho = st["rho"]
        H, W = rho.shape
        a = move.args
        v = move.verb

        def ival(name):
            try:
                x = float(a[name])
            except (KeyError, TypeError, ValueError):
                raise ValueError("%s: argument %s missing or not a number" % (v, name))
            if not math.isfinite(x) or x != int(x):
                raise ValueError("%s: argument %s must be an integer" % (v, name))
            return int(x)

        if v in ("FILL_RECT", "CLEAR_RECT"):
            x0, y0, x1, y1 = ival("x0"), ival("y0"), ival("x1"), ival("y1")
            if not (0 <= x0 <= x1 < W and 0 <= y0 <= y1 < H):
                raise ValueError("%s: rectangle (%d,%d)-(%d,%d) outside the %dx%d field or inverted"
                                 % (v, x0, y0, x1, y1, W, H))
            val = 1 if v == "FILL_RECT" else 0
            sub = rho[y0:y1 + 1, x0:x1 + 1]
            if not np.any(sub != val):
                raise ValueError("%s changes no cell" % v)
            sub[:] = val
        elif v in ("FILL_DISK", "CLEAR_DISK"):
            cx, cy = ival("cx"), ival("cy")
            try:
                r = float(a["r"])
            except (KeyError, TypeError, ValueError):
                raise ValueError("%s: radius missing" % v)
            if not (0 <= cx < W and 0 <= cy < H):
                raise ValueError("%s: centre (%d,%d) outside the %dx%d field" % (v, cx, cy, W, H))
            if not (math.isfinite(r) and R_MIN <= r <= R_MAX):
                raise ValueError("%s: radius %r outside [%g, %g]" % (v, r, R_MIN, R_MAX))
            val = 1 if v == "FILL_DISK" else 0
            m = _disk_mask(H, W, cx, cy, r)
            if not np.any(rho[m] != val):
                raise ValueError("%s changes no cell" % v)
            rho[m] = val
        elif v in ("SHIFT_FEATURE", "DILATE", "ERODE"):
            k = ival("k")
            an = self._analysis(st)
            labels, comps = an["labels"], an["comps"]
            if not (0 <= k < len(comps)):
                raise ValueError("%s: no component %d (there are %d)" % (v, k, len(comps)))
            mask = labels == k
            if v == "SHIFT_FEATURE":
                dx, dy = ival("dx"), ival("dy")
                if (dx == 0 and dy == 0) or abs(dx) > SHIFT_MAX or abs(dy) > SHIFT_MAX:
                    raise ValueError("SHIFT_FEATURE: (dx, dy) must be non-zero and |.| <= %d" % SHIFT_MAX)
                cells = np.argwhere(mask)
                ny, nx = cells[:, 0] + dy, cells[:, 1] + dx
                keep = (ny >= 0) & (ny < H) & (nx >= 0) & (nx < W)
                if not keep.any():
                    raise ValueError("SHIFT_FEATURE would push component %d off the field" % k)
                rho[mask] = 0
                rho[ny[keep], nx[keep]] = 1
            elif v == "DILATE":
                px = ival("px")
                if not (1 <= px <= DILATE_MAX):
                    raise ValueError("DILATE: px must be 1..%d" % DILATE_MAX)
                grown = ndimage.binary_dilation(mask, structure=_STRUCT8, iterations=px)
                add = grown & (rho == 0)
                if not add.any():
                    raise ValueError("DILATE changes no cell")
                rho[add] = 1
            else:
                px = ival("px")
                if not (1 <= px <= ERODE_MAX):
                    raise ValueError("ERODE: px must be 1..%d" % ERODE_MAX)
                kept = ndimage.binary_erosion(mask, structure=_STRUCT8, iterations=px, border_value=1)
                if not kept.any():
                    raise ValueError("ERODE would delete component %d entirely" % k)
                rho[mask & ~kept] = 0
        else:
            raise ValueError("engibench has no verb %r" % v)
        st["_an"] = None

    # ── program / reference ─────────────────────────────────────────────────
    def program(self, spec: dict) -> DesignProgram:
        fam = spec["family"]
        prog = program_from_goals(spec["goals"], objective_key=OBJECTIVE[fam],
                                  objective_ref=self.reference(spec), objective_sense="min",
                                  domain=self.name)
        return replace(prog, validity_bounds=tuple(VALIDITY[fam]))

    def reference(self, spec: dict) -> Optional[float]:
        ref = spec.get("ref_objective")
        if ref is None:
            st = {"fx": self._fixed(spec), "rho": _rows_decode(spec.get("ref_design") or spec["design0"]),
                  "_an": None}
            ref = self._analysis(st)["metrics"][OBJECTIVE[spec["family"]]]
            spec["ref_objective"] = float(ref)
        return float(ref)

    # ── greedy ──────────────────────────────────────────────────────────────
    def hint_move(self, st) -> Optional[Move]:
        """Depth-0 greedy: over the material budget -> clear a disk where the
        solid carries least; a performance limit violated -> fill a disk where
        the field works hardest across void; otherwise the fill if there is
        room under the budget, else the clear."""
        an = self._analysis(st)
        fx = st["fx"]
        fam = fx["family"]
        m = an["metrics"]
        goals = fx["spec"].get("goals", {})
        rho = st["rho"]
        S = an["proxy"]
        vol_key = "volume" if fam == "heatconduction2d" else (
            "material_fraction" if fam == "photonics2d" else "volume_fraction")
        vol_lim = goals.get("maximum_" + vol_key)
        over = vol_lim is not None and m.get(vol_key, 0.0) > vol_lim
        perf_bad = False
        for g, lim in goals.items():
            key = g.split("_", 1)[1]
            if key == vol_key:
                continue
            val = m.get(key)
            if val is None:
                continue
            if g.startswith("maximum_") and val > lim or g.startswith("minimum_") and val < lim:
                perf_bad = True
        fill = _nms_spots(S, rho == 0, 1, 1)
        clear = _nms_spots(-S, rho > 0, 1, 1)
        if over and clear:
            y, x = clear[0]
            return Move("CLEAR_DISK", {"cx": int(x), "cy": int(y), "r": 3.0})
        if (perf_bad or not over) and fill:
            y, x = fill[0]
            return Move("FILL_DISK", {"cx": int(x), "cy": int(y), "r": 3.0})
        if clear:
            y, x = clear[0]
            return Move("CLEAR_DISK", {"cx": int(x), "cy": int(y), "r": 2.0})
        return None

    # ── observation ─────────────────────────────────────────────────────────
    def move_label(self, st, move: Move) -> str:
        an = self._analysis(st)
        fx = st["fx"]
        rho = st["rho"]
        H, W = rho.shape
        a = move.args
        pn = PROXY_NAME[fx["family"]]
        try:
            if move.verb in ("SHIFT_FEATURE", "DILATE", "ERODE"):
                k = int(a["k"])
                c = an["comps"][k]
                share = self._comp_share(fx["family"], an, k)
                return ("component %d before this change: %d cells, x %d-%d, y %d-%d, %s"
                        % (k, c["size"], c["bbox"][0], c["bbox"][2], c["bbox"][1], c["bbox"][3],
                           self._share_txt(fx["family"], share)))
            if move.verb in ("FILL_RECT", "CLEAR_RECT"):
                m = np.zeros((H, W), dtype=bool)
                m[int(a["y0"]):int(a["y1"]) + 1, int(a["x0"]):int(a["x1"]) + 1] = True
            else:
                m = _disk_mask(H, W, int(a["cx"]), int(a["cy"]), float(a["r"]))
            fill = move.verb.startswith("FILL")
            chg = m & ((rho == 0) if fill else (rho > 0))
            n = int(chg.sum())
            if n == 0:
                return "changes no cell"
            return "%d %s cell%s become %s; mean %s there %s (field max %s)" % (
                n, "void" if fill else "solid", "" if n == 1 else "s", "solid" if fill else "void",
                pn, _num(float(an["proxy"][chg].mean())), _num(float(an["proxy"].max())))
        except Exception:
            return ""

    @staticmethod
    def _comp_share(fam: str, an: dict, k: int) -> float:
        """Fraction (0..1) of the family's quantity carried by component k: the ONE
        normalisation used by both the component table and move_label. The
        simulators store an['share'] in different units: beams2d absolute per-cell
        compliance (sums to the compliance), heatconduction2d absolute per-node
        dissipation (sums to J_T), photonics2d / thermoelastic2d already normalised
        (sum to 1); render_cot prints move_label on every history line, so an
        un-normalised share would print '25344%' there."""
        share = an["share"]
        raw = float(share[an["labels"] == k].sum())
        if fam == "beams2d":
            return raw / max(float(an["metrics"]["compliance"]), 1e-300)
        if fam == "photonics2d":
            return raw
        tot = float(share.sum()) if share.size else 0.0
        return raw / max(tot, 1e-300)

    @staticmethod
    def _share_txt(fam: str, share: float) -> str:
        if share < 1e-6:                 # round-off level: print as 0
            share = 0.0
        if fam == "beams2d":
            return "carries %s%% of the compliance" % _num(100 * share)
        if fam == "thermoelastic2d":
            return "carries %s%% of the weighted compliance" % _num(100 * share)
        if fam == "heatconduction2d":
            return "dissipates %s%% of the heat flow" % _num(100 * share)
        return "holds %s%% of the optical intensity on solid" % _num(100 * share)

