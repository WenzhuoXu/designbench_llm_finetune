    @staticmethod
    def _block(fam: str) -> int:
        return {"beams2d": 4, "thermoelastic2d": 4, "heatconduction2d": 5, "photonics2d": 4}[fam]

    @staticmethod
    def _digit_map(S: np.ndarray, b: int) -> List[str]:
        H, W = S.shape
        mx = float(S.max()) if S.size else 0.0
        lines = []
        if mx <= 0:
            return ["  (field is zero everywhere)"]
        for y0 in range(0, H, b):
            row = []
            for x0 in range(0, W, b):
                v = float(S[y0:y0 + b, x0:x0 + b].mean()) / mx
                if v < 1e-4:
                    row.append(".")
                else:
                    d = int(min(9, max(0, round(9 + 9 * math.log10(max(v, 1e-9)) / 4))))
                    row.append(str(d))
            lines.append("  y%-4d %s" % (y0, "".join(row)))
        return lines


