def _beam_state(nelx: int, nely: int, forcedist: float):
    """EngiBench's beams2d State (dof map, supports, load) for these conditions.
    The density filter rmin only serves the optimiser; simulate() never applies
    it, so the State is built with rmin = 1 (trivial filter, no 0.5 s loop)."""
    from engibench.problems.beams2d.backend import State
    key = (int(nelx), int(nely), round(float(forcedist), 9))
    if key not in _BEAM_STATES:
        _BEAM_STATES[key] = State.new(int(nelx), int(nely), 1.0, float(forcedist))
    return _BEAM_STATES[key]


def _sim_beams(fx: dict, rho: np.ndarray) -> dict:
    """EngiBench Beams2D.simulate, element by element: compliance
    c = sum_e (Emin + x^3 (Emax - Emin)) u_e^T k_e u_e with u from
    backend.calc_sensitivity (cvxopt cholmod on the SIMP stiffness)."""
    from engibench.problems.beams2d.backend import calc_sensitivity
    st = fx["bst"]
    nelx, nely = fx["W"], fx["H"]
    x = rho.astype(float).T.ravel()                     # image_to_design order (elx-major)
    try:
        ce = calc_sensitivity(x, st, {"penal": 3.0, "nelx": nelx, "nely": nely})
        # u_e^T k_e u_e >= 0 (k_e is PSD); cholmod round-off leaves ~1e-10
        # negatives on detached islands, which read as nonsense in the observation
        ce = np.maximum(ce, 0.0)
        e = (st.Emin + x ** 3 * (st.Emax - st.Emin)) * ce
        c = float(np.sum(e))
        if not math.isfinite(c):
            raise ArithmeticError("non-finite compliance")
        ce_img = ce.reshape(nelx, nely).T
        e_img = e.reshape(nelx, nely).T
    except Exception:
        c = 1e12
        ce_img = np.zeros((nely, nelx))
        e_img = np.zeros((nely, nelx))
    return {"objective": c, "metrics": {"compliance": c}, "proxy": ce_img, "share": e_img,
            "extra": {}}


def _thermo_mats():
    global _THERMO_MATS
    if _THERMO_MATS is None:
        from engibench.problems.thermoelastic2d.model.fem_matrix_builder import fe_melthm
        _THERMO_MATS = fe_melthm(0.3, 1.0, 1.0, 5e-4)   # nu, E, k, alpha (FeaModel.run)
    return _THERMO_MATS


def _sim_thermo(fx: dict, rho: np.ndarray) -> dict:
    """EngiBench ThermoElastic2D.simulate: FeaModel(eval_only) assembles and
    solves the thermal and the (thermally loaded) mechanical systems with
    fem_setup.fe_mthm_bc; the per-element energies that FeaModel sums in a
    Python loop are summed here vectorised (same formula, same numbers)."""
    from engibench.problems.thermoelastic2d.model.fem_setup import fe_mthm_bc
    ke, keth, cethm = _thermo_mats()
    nely, nelx = fx["H"], fx["W"]
    x = np.maximum(rho.astype(float), 1e-3)
    w = float(fx["weight"])
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            res = fe_mthm_bc(nely, nelx, 3, x, ke, keth, cethm, fx["tref"], fx["bcs"])
        elx, ely = (a.ravel() for a in np.meshgrid(np.arange(nelx), np.arange(nely), indexing="ij"))
        n1 = (nely + 1) * elx + ely
        n2 = (nely + 1) * (elx + 1) + ely
        edof4 = np.stack([n1 + 1, n2 + 1, n2, n1], axis=1)
        edof8 = np.stack([2 * n1 + 2, 2 * n1 + 3, 2 * n2 + 2, 2 * n2 + 3,
                          2 * n2, 2 * n2 + 1, 2 * n1, 2 * n1 + 1], axis=1)
        ume = res.um[edof8]
        uthe = res.uth[edof4]
        em = np.einsum("ei,ij,ej->e", ume, ke, ume)
        et = np.einsum("ei,ij,ej->e", uthe, keth, uthe)
        xp = x[ely, elx] ** 3
        sc = float(np.sum(xp * em))
        tc = float(np.sum(xp * et))
        if not (math.isfinite(sc) and math.isfinite(tc)):
            raise ArithmeticError("non-finite compliance")
        em_img = np.zeros((nely, nelx)); em_img[ely, elx] = em
        et_img = np.zeros((nely, nelx)); et_img[ely, elx] = et
        share = np.zeros((nely, nelx))
        share[ely, elx] = w * xp * em / max(sc, 1e-300) + (1 - w) * xp * et / max(tc, 1e-300)
        proxy = w * em_img / max(sc, 1e-300) + (1 - w) * et_img / max(tc, 1e-300)
        T = res.uth.reshape(nelx + 1, nely + 1).T          # [ny, nx]
    except Exception:
        sc = tc = 1e9
        em_img = et_img = proxy = share = np.zeros((nely, nelx))
        T = np.zeros((nely + 1, nelx + 1))
    cw = w * sc + (1 - w) * tc
    return {"objective": cw,
            "metrics": {"structural_compliance": sc, "thermal_compliance": tc,
                        "compliance_weighted": cw},
            "proxy": proxy, "share": share, "extra": {"em": em_img, "et": et_img, "T": T}}


def _heat_setup(N: int, length: float) -> dict:
    """Mesh and boundary data of the EngiBench heat-conduction template:
    UnitSquareMesh(N, N) with the 'right' diagonal, vertex v = ix + (N+1) iy at
    (ix/N, iy/N); T = 0 on x = 0, x = 1, y = 1 and on y = 0 outside the window
    |x - 1/2| <= length/2."""
    ix, iy = np.meshgrid(np.arange(N), np.arange(N), indexing="ij")
    ix = ix.ravel(); iy = iy.ravel()
    v00 = ix + (N + 1) * iy
    v10 = v00 + 1
    v01 = v00 + (N + 1)
    v11 = v01 + 1
    tri = np.concatenate([np.stack([v00, v10, v11]), np.stack([v00, v11, v01])], axis=1)
    xs = np.linspace(0.0, 1.0, N + 1)
    vx = np.tile(xs, N + 1)
    vy = np.repeat(xs, N + 1)
    p0, p1, p2 = tri
    det = (vx[p1] - vx[p0]) * (vy[p2] - vy[p0]) - (vx[p2] - vx[p0]) * (vy[p1] - vy[p0])
    gx = np.stack([vy[p1] - vy[p2], vy[p2] - vy[p0], vy[p0] - vy[p1]]) / det
    gy = np.stack([vx[p2] - vx[p1], vx[p0] - vx[p2], vx[p1] - vx[p0]]) / det
    A = 0.5 / (N * N)
    lb, ub = 0.5 - length / 2.0, 0.5 + length / 2.0
    bnd = (vx == 0.0) | (vy == 1.0) | (vx == 1.0) | ((vy == 0.0) & ((vx < lb) | (vx > ub)))
    free = np.nonzero(~bnd)[0]
    nv = (N + 1) ** 2
    b = np.zeros(nv)
    np.add.at(b, tri.ravel(), np.full(3 * tri.shape[1], 1e-2 * A / 3.0))
    rows = np.concatenate([tri[i] for i in range(3) for _ in range(3)])
    cols = np.concatenate([tri[j] for _ in range(3) for j in range(3)])
    gg = np.stack([A * (gx[i] * gx[j] + gy[i] * gy[j]) for i in range(3) for j in range(3)])
    return {"N": N, "tri": tri, "gx": gx, "gy": gy, "A": A, "bnd": bnd, "free": free, "b": b,
            "rows": rows, "cols": cols, "gg": gg, "nv": nv, "lb": lb, "ub": ub, "vx": vx, "vy": vy}


def _sim_heat(fx: dict, rho: np.ndarray) -> dict:
    """In-module P1 finite-element re-implementation of EngiBench's
    simulate_heat_conduction_2d.py (dolfin-adjoint): -div(k(a) grad T) = f on the
    unit square, k(a) = 1e-3 + (1 - 1e-3) a^5 with a the P1 nodal density,
    f = 1e-2, T = 0 on the sink boundary; objective J = int f T dx +
    1e-8 int |grad a|^2 dx. The element conductivity int_K k(a) dx is integrated
    EXACTLY (int_K phi0^p phi1^q phi2^r = 2A p!q!r!/(p+q+r+2)!), the load and
    objective integrals are exact for P1 data.
    Validation (2026-10-22, 8 dataset optima of IDEALLab/heat_conduction_2d_v0):
    J here vs the dataset's c: -3.0%, +0.8%, +1.2%, +2.4%, +2.8%, -8.0%, +6.5% and
    one row at -85% (that row's dataset value is inconsistent with its stored
    design under every boundary/orientation variant tried; the dataset's c is
    IPOPT's last logged objective, not a re-evaluation of the stored design).
    Alternative boundary placements and a transposed field are off by 50-180x,
    so the formulation here is the template's."""
    from scipy.sparse import coo_matrix
    from scipy.sparse.linalg import spsolve
    m = fx["mesh"]
    N = m["N"]
    design = rho[::-1, :].T.astype(float)              # rho[r, c] = design[ix=c, iy=N-r]
    a = design.T.ravel()                               # vertex order ix + (N+1) iy
    p0, p1, p2 = m["tri"]
    a0, a1, a2 = a[p0], a[p1], a[p2]
    h5 = np.zeros_like(a0)
    for p in range(6):
        for q in range(6 - p):
            h5 += a0 ** p * a1 ** q * a2 ** (5 - p - q)
    kb = 1e-3 + (1.0 - 1e-3) * h5 / 21.0
    vals = (m["gg"] * kb[None, :]).ravel()
    K = coo_matrix((vals, (m["rows"], m["cols"])), shape=(m["nv"], m["nv"])).tocsr()
    free = m["free"]
    T = np.zeros(m["nv"])
    try:
        T[free] = spsolve(K[free][:, free].tocsc(), m["b"][free])
        if not np.all(np.isfinite(T)):
            raise ArithmeticError("non-finite temperature")
    except Exception:
        T[:] = 1e3
    JT = float(np.dot(m["b"], T))
    gax = m["gx"][0] * a0 + m["gx"][1] * a1 + m["gx"][2] * a2
    gay = m["gy"][0] * a0 + m["gy"][1] * a1 + m["gy"][2] * a2
    Jreg = float(1e-8 * np.sum(m["A"] * (gax ** 2 + gay ** 2)))
    vol = float(np.sum(m["A"] * (a0 + a1 + a2) / 3.0))
    # dissipation k |grad T|^2 per triangle -> nodal (1/3 each); |grad T|^2 nodal mean = proxy
    gTx = m["gx"][0] * T[p0] + m["gx"][1] * T[p1] + m["gx"][2] * T[p2]
    gTy = m["gy"][0] * T[p0] + m["gy"][1] * T[p1] + m["gy"][2] * T[p2]
    g2 = gTx ** 2 + gTy ** 2
    diss = kb * g2 * m["A"]
    nod_diss = np.zeros(m["nv"]); np.add.at(nod_diss, m["tri"].ravel(), np.tile(diss / 3.0, 3))
    nod_g2 = np.zeros(m["nv"]); np.add.at(nod_g2, m["tri"].ravel(), np.tile(g2, 3))
    cnt = np.zeros(m["nv"]); np.add.at(cnt, m["tri"].ravel(), 1.0)
    nod_g2 /= np.maximum(cnt, 1.0)

    def to_rho(v):                                      # vertex vector -> [row, col]
        return v.reshape(N + 1, N + 1)[::-1, :]        # [iy, ix] -> row = N - iy

    J = JT + Jreg
    return {"objective": J,
            "metrics": {"thermal_compliance": J, "volume": vol,
                        "peak_temperature": float(np.max(T))},
            "proxy": to_rho(nod_g2), "share": to_rho(nod_diss),
            "extra": {"T": to_rho(T), "J_T": JT, "J_reg": Jreg}}


def _fix_phase(v: np.ndarray) -> np.ndarray:
    """Rotate a complex mode so its largest entry is real and positive: the
    eigenvector is unique only up to a global phase, which ARPACK draws at
    random per call (scipy eigs, v0=None), so fixing it makes the cached mode
    the same in every process."""
    v = np.asarray(v)
    k = int(np.argmax(np.abs(v)))
    a = v.flat[k]
    return v / (a / abs(a)) if abs(a) > 0 else v


def _phot_params(ph, cond: dict) -> dict:
    """Keyword arguments of epsr_parameterization exactly as Photonics2D._run_fdfd
    builds them (blur radius from the conditions, projection at the problem's
    current beta)."""
    return dict(bg_rho=ph._bg_rho, design_region=ph._design_region,
                radius=int(cond["blur_radius"]),
                num_blurs=cond.get("num_blurs", ph._num_blurs_default),
                beta=ph._current_beta, eta=cond.get("eta", ph._eta_default),
                num_projections=cond.get("num_projections", ph._num_projections_default),
                epsr_min=ph._epsr_min, epsr_max=ph._epsr_max)


def _phot_problem(lambda1: float, lambda2: float, blur: int):
    """(Photonics2D, conditions, modes) for these conditions, cached. The four
    port modes (source at lambda1 / lambda2 on the input slice, probe at lambda1
    on output 1, at lambda2 on output 2) are solved ONCE here on the background
    permittivity: the slices lie in the fixed waveguides outside the design
    window (x = 21 and 99 against a window of x = 30..89 at the default
    geometry; the slice permittivity was checked to be design-independent), so
    recomputing them per evaluation only added ARPACK's random phase, which
    broke bit-for-bit determinism of evaluate()."""
    key = (round(float(lambda1), 9), round(float(lambda2), 9), int(blur))
    if key not in _PHOT_PROBLEMS:
        from engibench.problems.photonics2d.backend import epsr_parameterization, insert_mode
        from engibench.problems.photonics2d.v0 import Photonics2D
        with contextlib.redirect_stdout(io.StringIO()):
            ph = Photonics2D(seed=0, config={"lambda1": float(lambda1), "lambda2": float(lambda2),
                                             "blur_radius": int(blur)})
            cond = ph._setup_simulation(None)
            epsr0 = epsr_parameterization(rho=np.zeros((ph.num_elems_x, ph.num_elems_y)),
                                          **_phot_params(ph, cond))
            si, o1, o2 = ph._input_slice, ph._output_slice1, ph._output_slice2
            modes = tuple(_fix_phase(insert_mode(om, ph._dl, sl.x, sl.y, epsr0, m=1))
                          for om, sl in ((ph.omega1, si), (ph.omega2, si),
                                         (ph.omega1, o1), (ph.omega2, o2)))
        _PHOT_PROBLEMS[key] = (ph, cond, modes)
    return _PHOT_PROBLEMS[key]


def _phot_fields(ph, cond: dict, modes, full: np.ndarray):
    """Photonics2D._run_fdfd with the cached modes: parameterise the full-grid
    density to permittivity and solve the two FDFD problems (ceviche fdfd_ez,
    scipy SuperLU: deterministic). Returns (epsr, ez1, ez2, probe1, probe2)."""
    from ceviche import fdfd_ez
    from engibench.problems.photonics2d.backend import epsr_parameterization
    source1, source2, probe1, probe2 = modes
    epsr = epsr_parameterization(rho=full, **_phot_params(ph, cond))
    npml = [ph._num_elems_pml, ph._num_elems_pml]
    _, _, ez1 = fdfd_ez(ph.omega1, ph._dl, epsr, npml).solve(source1)
    _, _, ez2 = fdfd_ez(ph.omega2, ph._dl, epsr, npml).solve(source2)
    return epsr, ez1, ez2, probe1, probe2


def _phot_geometry(ph) -> dict:
    """Design-region window and port rows (full-grid indices; rows = y)."""
    nx, ny = ph.num_elems_x, ph.num_elems_y
    off = ph._num_elems_pml + ph._pml_space
    x0, x1 = off, nx - off
    y0, y1 = off, ny - off
    wg = ph._wg_width
    in_y = (ny // 2 - wg // 2, ny // 2 + wg // 2 - 1)
    o1_y = (off + ph._wg_shift, off + ph._wg_shift + wg - 1)
    o2_y = (ny - off - wg - ph._wg_shift, ny - off - ph._wg_shift - 1)
    return {"x0": x0, "x1": x1, "y0": y0, "y1": y1, "wg": wg, "in_y": in_y, "o1_y": o1_y,
            "o2_y": o2_y, "dl_nm": ph._dl * 1e9, "pml": ph._num_elems_pml, "nx": nx, "ny": ny,
            "eps_min": ph._epsr_min, "eps_max": ph._epsr_max}


def _sim_phot(fx: dict, rho: np.ndarray) -> dict:
    """EngiBench Photonics2D.simulate without its prints: the design region is
    embedded in the full 120 x 120 grid, the density is parameterised (blur +
    projection + fixed waveguides -> permittivity) and two ceviche FDFD problems
    are solved with the problem's cached port modes (_phot_fields);
    overlap_i = |sum conj(Ez_i) probe_i| * 1e6. Checked against
    Photonics2D.simulate() on the same design: total_overlap - penalty agrees to
    1e-15 (rows 0 and 7, 2026-10-23)."""
    ph, cond = fx["ph"], fx["cond"]
    g = fx["geom"]
    full = np.zeros((g["nx"], g["ny"]), dtype=float)
    full[g["x0"]:g["x1"], g["y0"]:g["y1"]] = rho.T.astype(float)   # rho[row=y, col=x]
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            epsr, ez1, ez2, p1, p2 = _phot_fields(ph, cond, fx["modes"], full)
        o1 = float(np.abs(np.sum(np.conj(ez1) * p1)) * 1e6)
        o2 = float(np.abs(np.sum(np.conj(ez2) * p2)) * 1e6)
        if not (math.isfinite(o1) and math.isfinite(o2)):
            raise ArithmeticError("non-finite overlap")
        inten = (np.abs(ez1) ** 2 + np.abs(ez2) ** 2)[g["x0"]:g["x1"], g["y0"]:g["y1"]].T
        inten = inten / max(float(inten.max()), 1e-300)
    except Exception:
        o1 = o2 = 0.0
        inten = np.zeros(rho.shape)
    prod = o1 * o2
    loss = 1.0 / prod if prod > 0 else float("inf")
    penalty = float(ph._penalty_weight_default * np.linalg.norm(full))
    share = inten * (rho > 0)
    share = share / max(float(share.sum()), 1e-300)
    return {"objective": loss,
            "metrics": {"overlap1": o1, "overlap2": o2, "total_overlap": prod,
                        "coupling_loss": loss, "penalty": penalty},
            "proxy": inten, "share": share, "extra": {}}


