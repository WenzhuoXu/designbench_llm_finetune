def _unpack(bits: np.ndarray, shape) -> np.ndarray:
    n = int(shape[0]) * int(shape[1])
    return np.unpackbits(np.asarray(bits, dtype=np.uint8))[:n].reshape(int(shape[0]), int(shape[1])).astype(np.uint8)


def _rows_encode(rho: np.ndarray) -> List[str]:
    return ["".join("1" if v else "0" for v in row) for row in np.asarray(rho)]


def _rows_decode(rows: List[str]) -> np.ndarray:
    return np.array([[1 if ch == "1" else 0 for ch in r] for r in rows], dtype=np.uint8)


# ── field helpers ────────────────────────────────────────────────────────────
def _components(rho: np.ndarray):
    """(labels, comps): labels[y, x] = component label (largest = 0) or -1 for
    void; comps = list of dicts (size, bbox (x0, y0, x1, y1), centroid (x, y)).
    4-connectivity: cells are joined through shared edges (what carries load,
    heat or an optical mode between neighbouring cells)."""
    lab, n = ndimage.label(np.asarray(rho) > 0, structure=_STRUCT4)
    labels = np.full(rho.shape, -1, dtype=int)
    comps: List[dict] = []
    if n == 0:
        return labels, comps
    idx = np.arange(1, n + 1)
    sizes = ndimage.sum_labels(np.ones(rho.shape), lab, index=idx)
    flat = lab.ravel()
    first = np.full(n + 1, flat.size, dtype=int)
    # first raster cell of each label (deterministic tie-break)
    order_cells = np.nonzero(flat)[0]
    np.minimum.at(first, flat[order_cells], order_cells)
    order = sorted(range(n), key=lambda i: (-float(sizes[i]), int(first[i + 1])))
    objs = ndimage.find_objects(lab)
    # index is an array, so center_of_mass returns a list of (cy, cx) tuples
    # for every n >= 1 (a scalar index would return one bare tuple)
    coms = ndimage.center_of_mass(np.ones(rho.shape), lab, index=idx)
    for new, old in enumerate(order):
        labels[lab == old + 1] = new
        sl = objs[old]
        com = coms[old]
        comps.append({
            "size": int(sizes[old]),
            "bbox": (int(sl[1].start), int(sl[0].start), int(sl[1].stop - 1), int(sl[0].stop - 1)),
            "centroid": (float(com[1]), float(com[0])),
            "src": old + 1,
        })
    return labels, comps


def _disk_mask(H: int, W: int, cx: int, cy: int, r: float) -> np.ndarray:
    yy, xx = np.ogrid[:H, :W]
    return (yy - cy) ** 2 + (xx - cx) ** 2 <= r * r + 1e-9


def _nms_spots(score: np.ndarray, mask: np.ndarray, k: int, radius: int) -> List[Tuple[int, int]]:
    """Up to k (y, x) cells of the highest score inside mask, no two within
    Chebyshev distance < radius (deterministic: stable sort)."""
    s = np.where(mask, score, -np.inf).ravel()
    order = np.argsort(-s, kind="stable")
    out: List[Tuple[int, int]] = []
    W = score.shape[1]
    for flat in order[: max(400, 40 * k)]:
        if not np.isfinite(s[flat]):
            break
        y, x = int(flat // W), int(flat % W)
        if all(max(abs(y - y2), abs(x - x2)) >= radius for y2, x2 in out):
            out.append((y, x))
            if len(out) >= k:
                break
    return out


