# ── the domain ───────────────────────────────────────────────────────────────
class EngiBenchDomain(Domain):
    """EngiBench density-field problems with region verbs over labelled components."""

    name = "engibench"
    native_moves = True
    verbs = VERBS
    params = ()
    reference_class = "heuristic"
    stochastic = False

    def __init__(self, stochastic: bool = False):
        super().__init__(False)        # every EngiBench simulator here is deterministic

    # ── problem generation ──────────────────────────────────────────────────
    def make_problem(self, index: int, rng: np.random.Generator) -> dict:
        fam = FAMILIES[index % len(FAMILIES)]
        row = index // len(FAMILIES)
        if fam == "beams2d":
            spec = self._base_beams(row)
        elif fam == "thermoelastic2d":
            spec = self._base_thermo(row)
        elif fam == "heatconduction2d":
            spec = self._base_heat(row)
        else:
            spec = self._base_phot(row)
        return self._finish_problem(spec, rng)

    @staticmethod
    def _base_beams(row: int) -> dict:
        d = _data()
        n = d["beams_design_bits"].shape[0]
        i = row % n
        H, W = (int(v) for v in d["beams_shape"])
        B = _unpack(d["beams_design_bits"][i], (H, W))
        vf_ds = float(d["beams_volfrac"][i])
        # the stored design's own volume: equal to the dataset volfrac except for
        # the rows where exact-volume thresholding severed a strut (sidecar patch
        # of 2026-10-23: 2 of 40 rows, +0.020 and +0.025)
        vf = float(d["beams_volfrac_ref"][i]) if "beams_volfrac_ref" in d else vf_ds
        return {"family": "beams2d", "source": "IDEALLab/beams_2d_50_100_v0:test",
                "source_row": int(d["beams_row"][i]), "shape": [H, W],
                "volfrac": vf, "dataset_volfrac": vf_ds, "rmin": float(d["beams_rmin"][i]),
                "forcedist": float(d["beams_forcedist"][i]), "dataset_c": float(d["beams_c"][i]),
                "simulator": "engibench.problems.beams2d.backend (SIMP FE, cvxopt cholmod)",
                "_B": B}

    @staticmethod
    def _base_thermo(row: int) -> dict:
        d = _data()
        n = d["thermo_design_bits"].shape[0]
        i = row % n
        H, W = (int(v) for v in d["thermo_shape"])
        B = _unpack(d["thermo_design_bits"][i], (H, W))
        spec = {"family": "thermoelastic2d", "source": "IDEALLab/thermoelastic_2d_v0:test",
                "source_row": int(d["thermo_row"][i]), "shape": [H, W],
                "volfrac": float(d["thermo_volfrac"][i]), "weight": float(d["thermo_weight"][i]),
                "dataset_structural_compliance": float(d["thermo_sc"][i]),
                "dataset_thermal_compliance": float(d["thermo_tc"][i]),
                "simulator": "engibench.problems.thermoelastic2d.model (coupled FE, scipy spsolve)",
                "_B": B}
        for key, name in (("fixed", "fixed_nodes"), ("fx", "force_x_nodes"),
                          ("fy", "force_y_nodes"), ("hs", "sink_nodes")):
            lens = d["thermo_%s_len" % key]
            start = int(np.sum(lens[:i]))
            spec[name] = [int(v) for v in d["thermo_%s_idx" % key][start:start + int(lens[i])]]
        return spec

    @staticmethod
    def _base_heat(row: int) -> dict:
        d = _data()
        n = d["heat_design_bits"].shape[0]
        i = row % n
        N1 = int(d["heat_shape"][0])
        design = _unpack(d["heat_design_bits"][i], (N1, N1))      # design[ix, iy]
        B = design.T[::-1, :].copy()                                # rho[row = N - iy, col = ix]
        return {"family": "heatconduction2d", "source": "IDEALLab/heat_conduction_2d_v0:test+val",
                "source_row": int(i), "shape": [N1, N1],
                "volume": float(d["heat_volume"][i]), "length": float(d["heat_length"][i]),
                "dataset_c": float(d["heat_c"][i]),
                "simulator": "in-module P1 FEM re-implementation of EngiBench "
                             "simulate_heat_conduction_2d.py (dolfin-adjoint template)",
                "_B": B}

    @staticmethod
    def _base_phot(row: int) -> dict:
        d = _data()
        n = d["phot_design_bits"].shape[0]
        i = row % n
        nx, ny = (int(v) for v in d["phot_shape"])
        full = _unpack(d["phot_design_bits"][i], (nx, ny))         # rho[x, y]
        ph, _cond, _modes = _phot_problem(d["phot_lambda1"][i], d["phot_lambda2"][i], int(d["phot_blur"][i]))
        g = _phot_geometry(ph)
        B = full[g["x0"]:g["x1"], g["y0"]:g["y1"]].T.copy()         # [row = y, col = x]
        return {"family": "photonics2d", "source": "IDEALLab/photonics_2d_120_120_v0:test",
                "source_row": int(d["phot_row"][i]), "shape": [int(B.shape[0]), int(B.shape[1])],
                "lambda1": float(d["phot_lambda1"][i]), "lambda2": float(d["phot_lambda2"][i]),
                "blur_radius": int(d["phot_blur"][i]),
                "dataset_total_overlap": float(d["phot_total_overlap"][i]),
                "simulator": "engibench.problems.photonics2d (ceviche FDFD, scipy spsolve)",
                "_B": B}

    def _finish_problem(self, spec: dict, rng: np.random.Generator) -> dict:
        fam = spec["family"]
        B = spec.pop("_B")
        spec["design0"] = _rows_encode(B)
        spec["goals"] = {}
        fx = self._fixed(spec)
        ref_st = {"fx": fx, "rho": B.copy(), "_an": None}
        ref = self._analysis(ref_st)
        rm = dict(ref["metrics"])
        okey = OBJECTIVE[fam]
        u = rng.random()
        klass = "feasible" if u < 0.06 else ("near" if u < 0.42 else "deep")
        loose = klass == "feasible"
        goals: Dict[str, float] = {}
        if fam == "beams2d":
            goals["maximum_volume_fraction"] = float(spec["volfrac"])
            goals["maximum_compliance"] = rm["compliance"] * float(
                rng.uniform(1.5, 2.0) if loose else rng.uniform(1.1, 1.6))
        elif fam == "thermoelastic2d":
            goals["maximum_volume_fraction"] = float(spec["volfrac"])
            goals["maximum_structural_compliance"] = rm["structural_compliance"] * float(
                rng.uniform(1.5, 2.0) if loose else rng.uniform(1.1, 1.6))
            goals["maximum_thermal_compliance"] = rm["thermal_compliance"] * float(
                rng.uniform(1.4, 1.8) if loose else rng.uniform(1.05, 1.4))
        elif fam == "heatconduction2d":
            goals["maximum_volume"] = float(spec["volume"])
            goals["maximum_thermal_compliance"] = rm["thermal_compliance"] * float(
                rng.uniform(1.5, 2.0) if loose else rng.uniform(1.1, 1.6))
        else:
            q1 = float(rng.uniform(0.75, 0.9) if loose else rng.uniform(0.55, 0.85))
            q2 = float(rng.uniform(0.75, 0.9) if loose else rng.uniform(0.55, 0.85))
            goals["minimum_overlap1"] = rm["overlap1"] * q1
            goals["minimum_overlap2"] = rm["overlap2"] * q2
            goals["maximum_material_fraction"] = float(min(0.9, rm["material_fraction"]
                                                           * rng.uniform(1.25, 1.7)))
        spec["goals"] = {k: float(v) for k, v in goals.items()}
        spec["ref_objective"] = float(rm[okey])
        spec["ref_metrics"] = {k: float(v) for k, v in rm.items()}
        spec["ref_design"] = spec["design0"]
        prog = self.program(spec)

        # perturb with the domain's own verbs; keep the start inside the envelope
        st = {"fx": fx, "rho": B.copy(), "_an": None}
        n_pert = 1 if klass in ("feasible", "near") else 2 + int(rng.random() < 0.5)
        applied: List[str] = []
        kinds = ["blob", "grow", "notch", "shift", "thin"]
        wts = np.array([0.25, 0.2, 0.3, 0.12, 0.13])
        for _ in range(n_pert):
            kind = kinds[int(rng.choice(len(kinds), p=wts / wts.sum()))]
            if klass == "feasible":
                kind = "notch"
            mv = self._perturbation(st, kind, "near" if klass != "deep" else "deep", rng)
            if mv is None:
                continue
            trial = self.clone(st)
            try:
                self.apply(trial, mv)
            except ValueError:
                continue
            m = self._analysis(trial)["metrics"]
            if not prog.is_valid(m) or self._too_far(fam, m, rm):
                continue
            st = trial
            applied.append(self.format_move(mv))
        tries = 0
        while klass != "feasible" and tries < 4:
            m = self._analysis(st)["metrics"]
            if not prog.is_feasible(m):
                break
            mv = self._perturbation(st, "grow" if tries % 2 == 0 else "notch", "deep", rng)
            tries += 1
            if mv is None:
                continue
            trial = self.clone(st)
            try:
                self.apply(trial, mv)
            except ValueError:
                continue
            m2 = self._analysis(trial)["metrics"]
            if not prog.is_valid(m2) or self._too_far(fam, m2, rm):
                continue
            st = trial
            applied.append(self.format_move(mv))
        m0 = self._analysis(st)["metrics"]
        spec["design0"] = _rows_encode(st["rho"])
        spec["difficulty_class"] = "feasible" if prog.is_feasible(m0) else klass
        spec["perturbations"] = applied
        spec["initial_metrics"] = {k: float(v) for k, v in m0.items()}
        return spec

    @staticmethod
    def _too_far(fam: str, m: dict, ref: dict) -> bool:
        """A perturbed start must stay a design the simulator still describes
        sensibly (not a severed load path at 1e9 compliance)."""
        if fam == "beams2d":
            return m["compliance"] > 25.0 * ref["compliance"]
        if fam == "thermoelastic2d":
            return (m["structural_compliance"] > 25.0 * ref["structural_compliance"]
                    or m["thermal_compliance"] > 25.0 * ref["thermal_compliance"])
        if fam == "heatconduction2d":
            return m["thermal_compliance"] > 25.0 * ref["thermal_compliance"]
        return m["coupling_loss"] > 1e4 * ref["coupling_loss"]

    def _perturbation(self, st, kind: str, severity: str, rng) -> Optional[Move]:
        an = self._analysis(st)
        rho = st["rho"]
        H, W = rho.shape
        comps = an["comps"]
        S = an["proxy"]
        if kind == "blob":
            void = rho == 0
            if not void.any():
                return None
            cells = np.argwhere(void)
            y, x = cells[int(rng.integers(len(cells)))]
            r = float(rng.uniform(2.5, 4.5) if severity == "near" else rng.uniform(4.0, 7.0))
            if rng.random() < 0.4:
                w = int(rng.integers(2, 5)); h = int(rng.integers(6, 14))
                if rng.random() < 0.5:
                    w, h = h, w
                x0, y0 = int(min(x, W - w)), int(min(y, H - h))
                return Move("FILL_RECT", {"x0": x0, "y0": y0, "x1": x0 + w - 1, "y1": y0 + h - 1})
            return Move("FILL_DISK", {"cx": int(x), "cy": int(y), "r": round(r, 1)})
        if kind == "grow":
            if not comps:
                return None
            k = 0 if len(comps) == 1 or rng.random() < 0.7 else int(rng.integers(len(comps)))
            return Move("DILATE", {"k": k, "px": 1 if severity == "near" else int(rng.integers(1, 3))})
        if kind == "notch":
            solid = rho > 0
            if not solid.any():
                return None
            # a notch across loaded material: among the top-energy solid cells
            spots = _nms_spots(S, solid, 12, 4)
            if not spots:
                return None
            y, x = spots[int(rng.integers(min(len(spots), 8)))]
            w = int(rng.integers(2, 4)) if severity == "near" else int(rng.integers(3, 6))
            h = int(rng.integers(2, 4)) if severity == "near" else int(rng.integers(3, 6))
            x0, y0 = int(max(0, min(x - w // 2, W - w))), int(max(0, min(y - h // 2, H - h)))
            return Move("CLEAR_RECT", {"x0": x0, "y0": y0, "x1": x0 + w - 1, "y1": y0 + h - 1})
        if kind == "shift":
            small = [k for k, c in enumerate(comps) if k > 0 and c["size"] <= 0.2 * H * W]
            if not small:
                return None
            k = small[int(rng.integers(len(small)))]
            dx, dy = int(rng.integers(-5, 6)), int(rng.integers(-5, 6))
            if dx == 0 and dy == 0:
                dx = 3
            return Move("SHIFT_FEATURE", {"k": k, "dx": dx, "dy": dy})
        if kind == "thin":
            cand = [k for k, c in enumerate(comps) if c["size"] >= 12]
            if not cand:
                return None
            k = cand[int(rng.integers(min(len(cand), 3)))]
            return Move("ERODE", {"k": k, "px": 1})
        return None

    # ── state ───────────────────────────────────────────────────────────────
    def _fixed(self, spec: dict) -> dict:
        fam = spec["family"]
        H, W = int(spec["shape"][0]), int(spec["shape"][1])
        fx: dict = {"family": fam, "H": H, "W": W, "spec": spec}
        if fam == "beams2d":
            fx["bst"] = _beam_state(W, H, spec["forcedist"])
            fx["load_x"] = int(round(float(spec["forcedist"]) * W))
            fx["load_cell"] = (0, min(W - 1, fx["load_x"]))
            fx["roller_cell"] = (H - 1, W - 1)
        elif fam == "thermoelastic2d":
            nn = (W + 1, H + 1)

            def mask(ids):
                mk = np.zeros(nn[0] * nn[1], dtype=int)
                mk[np.asarray(ids, dtype=int)] = 1
                return mk.reshape(nn)                      # [nx, ny]
            fx["bcs"] = {"fixed_elements": mask(spec["fixed_nodes"]),
                         "force_elements_x": mask(spec["force_x_nodes"]),
                         "force_elements_y": mask(spec["force_y_nodes"]),
                         "heatsink_elements": mask(spec["sink_nodes"]), "weight": float(spec["weight"])}
            fx["weight"] = float(spec["weight"])
            fx["tref"] = 9.267e-4
            fx["nodes"] = {k: [(int(i) // nn[1], int(i) % nn[1]) for i in spec[k]]     # (nx, ny)
                           for k in ("fixed_nodes", "force_x_nodes", "force_y_nodes", "sink_nodes")}
        elif fam == "heatconduction2d":
            fx["mesh"] = _heat_setup(H - 1, float(spec["length"]))
        else:
            ph, cond, modes = _phot_problem(spec["lambda1"], spec["lambda2"], int(spec["blur_radius"]))
            fx["ph"], fx["cond"], fx["geom"], fx["modes"] = ph, cond, _phot_geometry(ph), modes
        return fx

    def load(self, spec: dict):
        fam = spec.get("family")
        if fam in STUB_FAMILIES:
            raise NotImplementedError("family %s is a stub in this domain (no simulator)" % fam)
        return {"fx": self._fixed(spec), "rho": _rows_decode(spec["design0"]), "_an": None}

    def clone(self, st):
        return {"fx": st["fx"], "rho": st["rho"].copy(), "_an": None}

    # ── simulation ──────────────────────────────────────────────────────────
    def _analysis(self, st) -> dict:
        an = st.get("_an")
        if an is None:
            fx = st["fx"]
            rho = st["rho"]
            if _tp_limits is not None:
                with _tp_limits(limits=1):
                    an = _SIMS[fx["family"]](fx, rho)
            else:
                an = _SIMS[fx["family"]](fx, rho)
            labels, comps = _components(rho)
            an["labels"], an["comps"] = labels, comps
            m = dict(an["metrics"])
            if fx["family"] == "photonics2d":
                m["material_fraction"] = float(rho.mean())
            elif fx["family"] != "heatconduction2d":
                m["volume_fraction"] = float(rho.mean())
            m["n_components"] = float(len(comps))
            if fx["family"] == "beams2d":
                m["attached_fraction"] = self._attached_fraction(fx, labels, comps)
            an["metrics"] = m
            st["_an"] = an
        return an

    @staticmethod
    def _attached_fraction(fx, labels, comps) -> float:
        """Share of the solid cells in components that touch a support (the
        symmetry plane x = 0 or the roller cell)."""
        if not comps:
            return 0.0
        touching = set(int(v) for v in labels[:, 0] if v >= 0)
        r = labels[fx["roller_cell"]]
        if r >= 0:
            touching.add(int(r))
        tot = sum(c["size"] for c in comps)
        return float(sum(comps[k]["size"] for k in touching) / max(tot, 1))

    def evaluate(self, st, seed: int = 0) -> dict:
        self.calls += 1
        an = self._analysis(st)
        return {k: float(v) for k, v in an["metrics"].items()}

