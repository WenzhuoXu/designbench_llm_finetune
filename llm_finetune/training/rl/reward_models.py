# ── Reward wrappers that use learned models in GRPO ──────────────────────────
class LearnedPRMReward:
    """Wraps a ProcessRewardModel for use as a GRPO RewardFunction.

    Computes mean PRM score across all steps in a rollout.
    Can be combined with rule-based rewards via CompositeReward.
    """

    def __init__(self, prm: ProcessRewardModel, weight: float = 1.0):
        self.prm = prm
        self.weight = weight

    def compute(self, rollout, problem_spec: dict) -> float:
        if not self.prm.is_loaded or not rollout.action_sequence:
            return 0.0

        scores = []
        for i, action in enumerate(rollout.action_sequence):
            state = rollout.state_history[i] if i < len(rollout.state_history) else {}
            thinking = ""
            if i < len(rollout.raw_outputs):
                # Extract thinking from raw output
                import re
                m = re.search(r"<think>(.*?)</think>", rollout.raw_outputs[i], re.DOTALL)
                thinking = m.group(1).strip() if m else ""
            score = self.prm.score(state, action, problem_spec, thinking)
            scores.append(score)

        return self.weight * (sum(scores) / len(scores))

    def name(self) -> str:
        return "learned_prm"
