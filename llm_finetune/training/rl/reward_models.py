"""
Learned Reward Models — Research Hook.

Skeleton implementations for Process Reward Models (PRM) and Outcome Reward Models
(ORM) trained on DesignBench data. These replace or augment rule-based reward
functions with learned models.

Training data sources:
  - PRM labels: generated by DesignBench's scripts/build_prm_labels.py
    Each step in a trace gets a score based on FEA improvement
  - ORM labels: binary feasibility of final design
  - Cost model: trained on token counts, FEA calls, constraint violations

Research directions:
  1. PRM: Score each intermediate reasoning step → better credit assignment
  2. ORM: Score final design → cleaner reward signal without intermediate bias
  3. Hybrid: PRM for exploration guidance, ORM for final evaluation
  4. Adversarial: reward model trained against a policy model (GAN-style)
  5. Uncertainty-aware: ensemble of reward models for exploration bonuses

To train a PRM:
    1. Run: python scripts/build_prm_labels.py (DesignBench)
    2. Load labels from data/prm_labels/
    3. Fine-tune a small LLM (e.g., Qwen2.5-1.5B) on (state, action) → score
    4. Load here: prm = ProcessRewardModel.from_pretrained("checkpoints/prm/")
    5. Use in GRPO: reward_fn = LearnedPRMReward(prm)

Usage:
    prm = ProcessRewardModel("Qwen/Qwen2.5-1.5B", "checkpoints/prm/step_1000/")
    prm.load()
    score = prm.score(state_dict, action_str, problem_spec)
"""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from pathlib import Path
from typing import Optional

import torch

log = logging.getLogger(__name__)


class LearnedRewardModel(ABC):
    """Abstract base class for learned reward/cost models.

    Research hook: implement score() to define the reward model's scoring logic.

    Training pipeline:
      1. Collect (state, action, label) data from DesignBench FEA or human feedback
      2. Fine-tune a base LLM or encoder model
      3. Load checkpoint here and use as reward signal in GRPO

    Key design decision: should the reward model be a regression model (continuous
    score) or a classification model (binary feasibility prediction)?
    For DesignBench, continuous FOS-based scores generally work better.
    """

    @abstractmethod
    def score(
        self,
        state: dict,
        action: str,
        problem_spec: dict,
        thinking: str = "",
    ) -> float:
        """Score a (state, action) pair.

        Args:
            state: Current design state (mass, fos_b, fos_y, member_dimensions).
            action: Grammar action string.
            problem_spec: Problem specification (goals, topology, loading).
            thinking: Optional thinking/reasoning text (for PRM that evaluates reasoning).

        Returns:
            Scalar score. Higher = better.
        """
        ...

    @abstractmethod
    def load_from_checkpoint(self, checkpoint_path: str | Path) -> None:
        """Load model weights from checkpoint directory."""
        ...

    @property
    def is_loaded(self) -> bool:
        return False

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}(loaded={self.is_loaded})"


class ProcessRewardModel(LearnedRewardModel):
    """Process Reward Model (PRM): scores intermediate reasoning steps.

    Trained to predict per-step quality labels generated by DesignBench's
    build_prm_labels.py script.

    Architecture:
        - Base: small causal LM (e.g., Qwen2.5-1.5B or a 7B model)
        - Head: scalar regression head on final [EOS] token
        - Input: state_text + action_text → single score
        - Training objective: MSE or ranking loss on FEA-derived labels

    Research questions this enables:
      - Does step-level supervision improve sample efficiency?
      - Can PRM identify "dead ends" before full trajectory completion?
      - Can PRM replace FEA simulation for fast reward estimation?
    """

    def __init__(
        self,
        base_model_id: str = "Qwen/Qwen2.5-1.5B-Instruct",
        checkpoint_path: Optional[str | Path] = None,
        device: str = "cuda",
        dtype: torch.dtype = torch.bfloat16,
    ):
        self.base_model_id = base_model_id
        self.checkpoint_path = checkpoint_path
        self.device = device
        self.dtype = dtype
        self._model = None
        self._tokenizer = None

        if checkpoint_path is not None:
            self.load_from_checkpoint(checkpoint_path)

    def score(
        self,
        state: dict,
        action: str,
        problem_spec: dict,
        thinking: str = "",
    ) -> float:
        if self._model is None:
            log.warning("PRM not loaded. Returning 0.0")
            return 0.0

        input_text = self._format_input(state, action, thinking)
        inputs = self._tokenizer(
            input_text,
            return_tensors="pt",
            truncation=True,
            max_length=512,
        ).to(self.device)

        with torch.no_grad():
            outputs = self._model(**inputs)
            # Score from regression head (last hidden state → linear)
            score = outputs.logits[:, -1, 0].item()  # adjust based on head architecture

        return float(score)

    def load_from_checkpoint(self, checkpoint_path: str | Path) -> None:
        """Load fine-tuned PRM checkpoint.

        Expected checkpoint structure:
            checkpoint_path/
                config.json
                model.safetensors (or pytorch_model.bin)
                tokenizer.json
                tokenizer_config.json
        """
        from transformers import AutoModelForCausalLM, AutoTokenizer
        checkpoint_path = Path(checkpoint_path)
        if not checkpoint_path.exists():
            log.warning(f"PRM checkpoint not found: {checkpoint_path}")
            return

        log.info(f"Loading PRM from {checkpoint_path} ...")
        self._tokenizer = AutoTokenizer.from_pretrained(str(checkpoint_path))
        self._model = AutoModelForCausalLM.from_pretrained(
            str(checkpoint_path),
            torch_dtype=self.dtype,
            device_map=self.device,
        )
        self._model.eval()
        log.info("PRM loaded")

    @property
    def is_loaded(self) -> bool:
        return self._model is not None

    def _format_input(self, state: dict, action: str, thinking: str = "") -> str:
        """Format (state, action) pair as text input for the PRM."""
        lines = [
            f"State: mass={state.get('mass', '?'):.4f}, "
            f"fos_b={state.get('fos_buckling', '?'):.4f}, "
            f"fos_y={state.get('fos_yielding', '?'):.4f}",
            f"Action: {action}",
        ]
        if thinking:
            lines.insert(0, f"Reasoning: {thinking[:200]}")  # truncate long thinking
        return "\n".join(lines)


